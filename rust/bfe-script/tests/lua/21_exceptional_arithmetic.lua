-- Exceptional arithmetic: ways a script makes NaN, infinity, negative zero or a
-- subnormal number. Each result goes into `results` (the test checks the bits of
-- every NaN) and is printed with its reciprocal, NaN as the word "NaN".
local inf = 1 / 0
local nan = 0 / 0
results = {}
local function add(label, v)
  table.insert(results, v)
  if v ~= v then
    print(label, "NaN")
  else
    print(label, v, 1 / v)
  end
end

-- operators
add("0/0", 0 / 0)
add("inf-inf", inf - inf)
add("inf*0", inf * 0)
add("-nan", -nan)
add("nan+1", nan + 1)
add("nan*0", nan * 0)
add("inf/inf", inf / inf)
add("1/0", 1 / 0)
add("-1/0", -1 / 0)
add("0*-1", 0 * -1)
add("-0+0", (0 * -1) + 0)
add("-0-0", (0 * -1) - 0)
add("tiny/2", 1e-45 / 2)
add("tiny*tiny", 1e-40 * 1e-5)
add("big*10", 3.4e38 * 10)
add("2^128", 2 ^ 128)
add("2^-149", 2 ^ -149)
add("2^-150", 2 ^ -150)
add("(-8)^(1/3)", (-8) ^ (1 / 3))
add("0^-1", 0 ^ -1)
add("(-0)^-1", (0 * -1) ^ -1)
add("inf^0", inf ^ 0)
add("nan^0", nan ^ 0)
add("1^nan", 1 ^ nan)
add("(-1)^inf", (-1) ^ inf)
add("subnormal+subnormal", 1e-45 + 1e-45)
add("max-max", 3.4028235e38 - 3.4028235e38)

