-- values kept in tables, upvalues and loop variables
local t = {}
t[1] = nan
t.k = -nan
add("t[1]", t[1])
add("t.k", t.k)
local function keep(v) return function() return v end end
add("upvalue", keep(-nan)())
local steps = 0
for i = 1, nan do steps = steps + 1 end
for i = nan, 1 do steps = steps + 1 end
print("nan loops", steps)
print("compare", nan == nan, nan ~= nan, nan < 1, nan > 1, nan <= nan, inf == inf, -inf < inf)
print("index", pcall(function() local u = {} u[nan] = 1 end))
print("read", ({})[nan])
