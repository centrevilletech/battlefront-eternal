#[test]
fn legacy_mounted_snapshot_and_position_deltas() {
    let mut rows = [
        WireRecord { kind: Kind::Soldier, id: 31., generation: 3., class_id: Some(4.), team: Some(1.),
            health: Some(95.), state: WireRecordState::F64(2.), weapon: 5., yaw: Some(0.5), pitch: Some(-0.25),
            position: Some([-42., 2., 250.]), velocity: Some([0.5, -1., 2.]), ..Default::default() },
        WireRecord { kind: Kind::Vehicle, id: 45., generation: 2., class_id: Some(7.), team: Some(1.),
            health: Some(400.), power: 55., state: WireRecordState::F64(1.), quaternion: Some([0., 0., 0., 1.]),
            position: Some([-43., 0., 250.]), ..Default::default() },
        WireRecord { kind: Kind::Mount, id: 45., slot: Some(2.), walk_phase: 0.75, walk_blend: 0.5,
            seats: Some(vec![WireSeatAngles { yaw: 0.25, pitch: -0.5 }]), ..Default::default() },
        WireRecord { kind: Kind::Seat, id: 31., vehicle_id: Some(45.), seat_index: Some(0.), ..Default::default() },
    ];
    let strings = Strings::default();
    let mut runtime = Runtime::default();
    runtime.reserve_world(1, 0).unwrap();
    for tick in 10..=12 {
        let tick = f64::from(tick);
        if tick > 10. {
            rows[0].position = Some([-42. + (tick - 10.) * 0.25, 2., 250.]);
        }
        if tick == 12. {
            rows[3].vehicle_id = None;
        }
        runtime.capture_canonical(tick, 1., &rows, std::iter::empty(), &strings).unwrap();
        let baseline = if tick == 10. { 0. } else { tick - 1. };
        let parts = runtime.encode(tick, 1., baseline, 1.).unwrap();
        assert_eq!(parts.len(), 1);
        let expected = [MOUNTED, RIDER_MOVE, DISMOUNT][tick as usize - 10];
        assert_eq!(parts[0], expected);
    }
}

#[test]
fn legacy_compact_launch_and_impact() {
    let mut journal = Events::default();
    for (index, schema) in [1., 2.].into_iter().enumerate() {
        let bolt = WbEncode { schema, id: 9., generation: 2., tick: 10., expiry_tick: 22.,
            definition_id: 4., owner_id: 5., owner_generation: 2., fire_id: 7., channel: 1.,
            launch_tick: 9.25, execution_tick: 10., surface: 3., position_array: true,
            direction_array: true, offset_array: true, position: vec![-73.5, 41., 233.25],
            direction: vec![0., 0., 1.], offset: vec![0.5, -0.25, 1.5],
            life: 1.5, speed: 20., merge: 0.5, ..Default::default() };
        let payload = combat::bolt(&bolt).unwrap();
        journal.emit_raw(bolt.id, bolt.generation, bolt.tick, schema, &payload, Default::default());
        assert_eq!(journal.cosmetics()[index].bytes, [LAUNCH, IMPACT][index]);
    }
}
