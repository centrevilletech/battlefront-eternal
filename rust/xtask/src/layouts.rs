// Numeric boundary layout generators (`layouts.rs`).
//
// Emits Rust (`rust/.../*layout.rs`) constant modules from JSON schema files
// or inline tables:
// - `presentation_schema`
// - `environment_schema`
// - `transport_schema`
// - `audio_control_schema`
// - `audio_schema`
// - `audio_codec_schema`
//
// Byte-identical formatting and ordering rules:
// 1. Property order in every emitted module matches the source `.json` file or
//    static table insertion order.
// 2. Identifier case conversion rules are preserved per generator:
//    - `upper_camel` inserts `_` before every uppercase letter except at index 0,
//      so consecutive capitals split (e.g. `2D` -> `2_D`).
//    - `upper_transport` only inserts `_` between a lowercase/digit character
//      and an uppercase character.
// 3. Generated header banners keep the historical `// Generated by tools/<name>.mjs; do not edit.`
//    first line and end every file with a single trailing `\n`.

use crate::json::{quote_str, JsonValue};
use std::collections::HashMap;
use std::fs;
use std::path::Path;

// Every ASCII uppercase character at `i > 0` is preceded by `_`, even when
// preceded by another uppercase letter or digit. The lowercase form of
// `upper_camel(name)` is also used for the Rust `pub mod <name>` identifier.
fn upper_camel(s: &str) -> String {
    let mut out = String::new();
    for (i, c) in s.chars().enumerate() {
        if c.is_ascii_uppercase() {
            if i > 0 {
                out.push('_');
            }
            out.push(c);
        } else {
            out.push(c.to_ascii_uppercase());
        }
    }
    out
}

// Inserts an underscore only when an ASCII lowercase letter or digit is
// immediately followed by an ASCII uppercase letter.
fn upper_transport(s: &str) -> String {
    let chars: Vec<char> = s.chars().collect();
    let mut out = String::new();
    for i in 0..chars.len() {
        let c = chars[i];
        out.push(c.to_ascii_uppercase());
        if i + 1 < chars.len()
            && (c.is_ascii_lowercase() || c.is_ascii_digit())
            && chars[i + 1].is_ascii_uppercase()
        {
            out.push('_');
        }
    }
    out
}

// Writes `expected` to `root/rel_path`, or in `--check` mode verifies that the
// existing file on disk is byte-for-byte identical to `expected` (treating a
// missing file as stale).
pub fn write_or_check(
    root: &Path,
    rel_path: &str,
    expected: &str,
    check: bool,
    err_msg: &str,
) -> Result<(), String> {
    let full = root.join(rel_path);
    if check {
        let have = fs::read_to_string(&full).ok();
        if have.as_deref() != Some(expected) {
            return Err(err_msg.to_string());
        }
    } else {
        if let Some(parent) = full.parent() {
            fs::create_dir_all(parent).map_err(|e| e.to_string())?;
        }
        fs::write(&full, expected).map_err(|e| e.to_string())?;
    }
    Ok(())
}

// Defines the numeric boundary across the 15 presentation, pose, audio-control,
// and render layout schemas under `rust/sim/schema/` and `rust/bfe-render/schema/`.
pub fn presentation_schema(root: &Path, check: bool) -> Result<(), String> {
    const LAYOUTS: &[(&str, &str)] = &[
        (
            "../../bfe-render/schema/scene-pose-layout.json",
            "rust/bfe-presentation/src/scene_pose_layout.rs",
        ),
        (
            "../../bfe-render/schema/scene-pose-layout.json",
            "rust/bfe-render/src/scene_pose_layout.rs",
        ),
        (
            "../../bfe-render/schema/scene-transform-layout.json",
            "rust/bfe-render/src/scene_transform_layout.rs",
        ),
        (
            "visual-effects-layout.json",
            "rust/bfe-presentation/src/visual_effects_layout.rs",
        ),
        (
            "lightning-layout.json",
            "rust/bfe-presentation/src/effects/lightning_layout.rs",
        ),
        (
            "sniper-layout.json",
            "rust/bfe-presentation/src/sniper_layout.rs",
        ),
        (
            "network-layout.json",
            "rust/bfe-presentation/src/network_layout.rs",
        ),
        (
            "interface-batch-layout.json",
            "rust/bfe-presentation/src/interface_batch_layout.rs",
        ),
        (
            "shell-music-layout.json",
            "rust/audio-control/src/shell_music_layout.rs",
        ),
        (
            "page-layout.json",
            "rust/bfe-presentation/src/page_layout.rs",
        ),
        (
            "presentation-layout.json",
            "rust/bfe-presentation/src/layout.rs",
        ),
        (
            "ordnance-layout.json",
            "rust/bfe-presentation/src/ordnance_layout.rs",
        ),
        (
            "timeline-layout.json",
            "rust/bfe-pose/src/timeline_layout.rs",
        ),
        (
            "items-layout.json",
            "rust/bfe-presentation/src/items_layout.rs",
        ),
        ("scene-layout.json", "rust/bfe-render/src/scene_layout.rs"),
    ];

    for &(schema, rs_path) in LAYOUTS {
        let schema_path = root.join("rust/sim/schema").join(schema);
        let text = fs::read_to_string(&schema_path).map_err(|e| e.to_string())?;
        let doc = JsonValue::parse(&text)?;
        let version = doc
            .get("version")
            .and_then(|v| v.as_u32())
            .ok_or("missing version")?;
        let empty = Vec::new();
        let mut records = doc
            .get("records")
            .and_then(|v| v.as_object())
            .map(|s| s.to_vec())
            .unwrap_or_default();
        let enums = doc.get("enums").and_then(|v| v.as_object()).unwrap_or(&empty);
        let limits = doc.get("limits").and_then(|v| v.as_object()).unwrap_or(&empty);
        let shared_rust_limits = doc
            .get("sharedRustLimits")
            .and_then(|v| v.as_object())
            .unwrap_or(&empty);
        let imports = doc.get("imports").and_then(|v| v.as_object()).unwrap_or(&empty);

        // Imported source rows keep the pose join tied to the original producer ABI.
        for (name, source) in imports {
            let imp_file = source
                .get("file")
                .and_then(|v| v.as_str())
                .ok_or("missing import file")?;
            let imp_rec = source
                .get("record")
                .and_then(|v| v.as_str())
                .ok_or("missing import record")?;
            let imp_text = fs::read_to_string(root.join("rust/sim/schema").join(imp_file))
                .map_err(|e| e.to_string())?;
            let imp_doc = JsonValue::parse(&imp_text)?;
            let rec_val = imp_doc
                .get("records")
                .and_then(|r| r.get(imp_rec))
                .cloned()
                .ok_or_else(|| format!("Unknown imported record {name}"))?;
            if let Some(existing) = records.iter_mut().find(|(k, _)| k == name) {
                existing.1 = rec_val;
            } else {
                records.push((name.clone(), rec_val));
            }
        }

        let mut rs = format!(
            "// Generated by tools/presentation-schema.mjs; do not edit.\npub const VERSION: u32 = {version};\n"
        );

        // Packed fields retain schema order: hosts and kernels address the same
        // scalar words, including holes explicitly described as field widths.
        for (name, fields_val) in &records {
            let fields = fields_val.as_object().ok_or("record must be object")?;
            let mut at: usize = 0;
            let mut values = Vec::new();
            for (field, n_val) in fields {
                let n = n_val.as_usize().ok_or("field width must be number")?;
                values.push((upper_camel(field), JsonValue::Number(at as f64)));
                at += n;
            }
            values.push(("STRIDE".to_string(), JsonValue::Number(at as f64)));
            let mod_name = upper_camel(name).to_lowercase();
            let rs_lines: Vec<String> = values
                .iter()
                .map(|(k, v)| format!("    pub const {k}: usize = {};", v.as_usize().unwrap()))
                .collect();
            rs.push_str(&format!("pub mod {mod_name} {{\n{}\n}}\n", rs_lines.join("\n")));
        }

        // Enum order is also ABI: emit the same ordinal for consumers.
        for (name, names_val) in enums {
            let names = names_val.as_array().ok_or("enum must be array")?;
            let mut values = Vec::new();
            for (i, n_val) in names.iter().enumerate() {
                let n = n_val.as_str().ok_or("enum variant must be string")?;
                values.push((upper_camel(n), JsonValue::Number(i as f64)));
            }
            let mod_name = upper_camel(name).to_lowercase();
            let rs_lines: Vec<String> = values
                .iter()
                .map(|(k, v)| format!("    pub const {k}: u32 = {};", v.as_usize().unwrap()))
                .collect();
            rs.push_str(&format!("pub mod {mod_name} {{\n{}\n}}\n", rs_lines.join("\n")));
        }

        // Bounds accompany offsets so registration and fixed scratch agree.
        for (name, values_val) in limits {
            let values = values_val.as_object().ok_or("limit must be object")?;
            let mut fields = Vec::new();
            for (k, v) in values {
                fields.push((upper_camel(k), v.clone()));
            }
            let mod_name = upper_camel(name).to_lowercase();
            let rs_lines: Vec<String> = fields
                .iter()
                .map(|(k, v)| format!("    pub const {k}: usize = {};", v.as_usize().unwrap()))
                .collect();
            rs.push_str(&format!("pub mod {mod_name} {{\n{}\n}}\n", rs_lines.join("\n")));
        }

        // Shared detector limits belong to this schema even when a lower-level
        // crate consumes them. Emit a small module without a presentation dependency.
        let mut outputs = vec![(rs_path.to_string(), rs)];
        for (name, path_val) in shared_rust_limits {
            let path = path_val
                .as_str()
                .ok_or("sharedRustLimits path must be string")?;
            let values = limits
                .iter()
                .find(|(k, _)| k == name)
                .and_then(|(_, v)| v.as_object())
                .ok_or_else(|| format!("Unknown shared limit {name}"))?;
            let lines: Vec<String> = values
                .iter()
                .map(|(k, v)| format!("pub const {}: usize = {};", upper_camel(k), v.as_usize().unwrap()))
                .collect();
            outputs.push((
                path.to_string(),
                format!(
                    "// Generated by tools/presentation-schema.mjs from {schema}; do not edit.\n{}\n",
                    lines.join("\n")
                ),
            ));
        }

        // Check every consumer, including modules outside presentation, so a
        // schema edit cannot leave one crate accepting a different row count.
        for (path, value) in outputs {
            write_or_check(
                root,
                &path,
                &value,
                check,
                &format!("{path} needs regeneration"),
            )?;
        }
    }
    Ok(())
}

// Generates the numeric boundary of the destruction and weather presentation phase
// (`rust/bfe-environment`) from `rust/bfe-environment/layout.json` into
// `rust/bfe-environment/src/layout.rs`.
pub fn environment_schema(root: &Path, check: bool) -> Result<(), String> {
    let layout_path = root.join("rust/bfe-environment/layout.json");
    let text = fs::read_to_string(&layout_path).map_err(|e| e.to_string())?;
    let layout = JsonValue::parse(&text)?;
    let version = layout
        .get("version")
        .and_then(|v| v.as_u32())
        .ok_or("missing version")?;
    let empty = Vec::new();
    let records = layout
        .get("records")
        .and_then(|v| v.as_object())
        .unwrap_or(&empty);
    let enums = layout
        .get("enums")
        .and_then(|v| v.as_object())
        .unwrap_or(&empty);
    let limits = layout
        .get("limits")
        .and_then(|v| v.as_object())
        .unwrap_or(&empty);
    let blocks = layout
        .get("blocks")
        .and_then(|v| v.as_object())
        .unwrap_or(&empty);

    // Convert `MAX_PARTICLES` into `maxParticles` when resolving `Limits.FIELD`.
    let to_camel = |s: &str| -> String {
        let lower = s.to_lowercase();
        let mut out = String::new();
        let mut cap = false;
        for c in lower.chars() {
            if c == '_' {
                cap = true;
            } else if cap {
                out.push(c.to_ascii_uppercase());
                cap = false;
            } else {
                out.push(c);
            }
        }
        out
    };

    // Evaluates a number, a symbolic reference `Owner.FIELD` / `Owner.STRIDE`,
    // or a `*`-separated product.
    let resolve = |val: &JsonValue, strides: &HashMap<String, usize>| -> Result<usize, String> {
        let text = match val {
            JsonValue::Number(n) => (*n as usize).to_string(),
            JsonValue::String(s) => s.clone(),
            _ => return Err("cannot resolve non-string/number".into()),
        };
        let mut product: usize = 1;
        for raw_token in text.split('*') {
            let token = raw_token.trim();
            if token.chars().all(|c| c.is_ascii_digit()) && !token.is_empty() {
                product *= token.parse::<usize>().unwrap();
                continue;
            }
            let parts: Vec<&str> = token.split('.').collect();
            if parts.len() != 2 {
                return Err(format!("layout.json: cannot resolve {token}"));
            }
            let (owner, field) = (parts[0], parts[1]);
            let camel = to_camel(field);
            let limit_val = limits
                .iter()
                .find(|(k, _)| k == owner)
                .and_then(|(_, v)| v.get(&camel))
                .and_then(|v| v.as_usize());
            let resolved = limit_val.or_else(|| {
                if field == "STRIDE" {
                    strides.get(owner).copied()
                } else {
                    None
                }
            });
            match resolved {
                Some(v) => product *= v,
                None => return Err(format!("layout.json: cannot resolve {token}")),
            }
        }
        Ok(product)
    };

    let mut strides = HashMap::new();
    let mut rs = format!(
        "// Generated by tools/environment-schema.mjs; do not edit.\npub const VERSION: u32 = {version};\n"
    );

    // Emit packed record field offsets and record `STRIDE` values for subsequent `blocks` resolution.
    for (name, fields_val) in records {
        let fields = fields_val.as_object().ok_or("record must be object")?;
        let mut at: usize = 0;
        let mut values = Vec::new();
        for (field, n_val) in fields {
            values.push((upper_camel(field), JsonValue::Number(at as f64)));
            at += resolve(n_val, &strides)?;
        }
        values.push(("STRIDE".to_string(), JsonValue::Number(at as f64)));
        strides.insert(name.clone(), at);
        let mod_name = upper_camel(name).to_lowercase();
        let rs_lines: Vec<String> = values
            .iter()
            .map(|(k, v)| format!("    pub const {k}: usize = {};", v.as_usize().unwrap()))
            .collect();
        rs.push_str(&format!("pub mod {mod_name} {{\n{}\n}}\n", rs_lines.join("\n")));
    }

    // Emit enum ordinal constants (`f64` with `.0` in Rust).
    for (name, names_val) in enums {
        let names = names_val.as_array().ok_or("enum must be array")?;
        let mut values = Vec::new();
        for (i, n_val) in names.iter().enumerate() {
            let n = n_val.as_str().ok_or("enum variant must be string")?;
            values.push((upper_camel(n), JsonValue::Number(i as f64)));
        }
        let mod_name = upper_camel(name).to_lowercase();
        let rs_lines: Vec<String> = values
            .iter()
            .map(|(k, v)| format!("    pub const {k}: f64 = {}.0;", v.as_usize().unwrap()))
            .collect();
        rs.push_str(&format!("pub mod {mod_name} {{\n{}\n}}\n", rs_lines.join("\n")));
    }

    // Emit capacity limits.
    for (name, values_val) in limits {
        let values = values_val.as_object().ok_or("limit must be object")?;
        let mut fields = Vec::new();
        for (k, v) in values {
            fields.push((upper_camel(k), v.clone()));
        }
        let mod_name = upper_camel(name).to_lowercase();
        let rs_lines: Vec<String> = fields
            .iter()
            .map(|(k, v)| format!("    pub const {k}: usize = {};", v.as_usize().unwrap()))
            .collect();
        rs.push_str(&format!("pub mod {mod_name} {{\n{}\n}}\n", rs_lines.join("\n")));
    }

    // Named blocks laid end to end: where each entry starts, and the whole's length
    // (in the units of the strides given).
    for (name, block_val) in blocks {
        let start_val = block_val.get("start").ok_or("block missing start")?;
        let mut at = resolve(start_val, &strides)?;
        let entries = block_val
            .get("entries")
            .and_then(|v| v.as_array())
            .ok_or("block missing entries")?;
        let mut values = Vec::new();
        for entry_val in entries {
            let arr = entry_val.as_array().ok_or("block entry must be array")?;
            let entry_name = arr[0].as_str().ok_or("entry name must be string")?;
            values.push((upper_camel(entry_name), JsonValue::Number(at as f64)));
            at += resolve(&arr[1], &strides)? * resolve(&arr[2], &strides)?;
        }
        values.push(("LEN".to_string(), JsonValue::Number(at as f64)));
        let mod_name = upper_camel(name).to_lowercase();
        let rs_lines: Vec<String> = values
            .iter()
            .map(|(k, v)| format!("    pub const {k}: usize = {};", v.as_usize().unwrap()))
            .collect();
        rs.push_str(&format!("pub mod {mod_name} {{\n{}\n}}\n", rs_lines.join("\n")));
    }

    let path = "rust/bfe-environment/src/layout.rs";
    write_or_check(
        root,
        path,
        &rs,
        check,
        &format!("{path} needs regeneration: cargo xtask environment-schema"),
    )
}

// BFE-UDP/1 wire constants, byte-width packet records, and gameplay input names
// generated from `rust/sim/schema/transport-layout.json` into
// `rust/bfe-transport/src/layout.rs`.
pub fn transport_schema(root: &Path, check: bool) -> Result<(), String> {
    let schema_path = root.join("rust/sim/schema/transport-layout.json");
    let text = fs::read_to_string(&schema_path).map_err(|e| e.to_string())?;
    let schema = JsonValue::parse(&text)?;
    let version = schema
        .get("version")
        .and_then(|v| v.as_usize())
        .ok_or("missing version")?;

    let mut rs = format!(
        "// Generated by tools/transport-schema.mjs; do not edit.\npub const VERSION: usize = {version};\n"
    );

    let mut group = |name: &str, values: &JsonValue| -> Result<(), String> {
        rs.push_str(&format!("pub mod {} {{\n", name.to_lowercase()));
        for (key, value) in values.as_object().ok_or("group values must be object")? {
            let ty = match value {
                JsonValue::String(_) => "&str",
                JsonValue::Number(n) if *n > 0xffff_ffffu64 as f64 => "u64",
                _ => "usize",
            };
            rs.push_str(&format!(
                "    pub const {}: {ty} = {};\n",
                upper_transport(key),
                value.to_json_compact()
            ));
        }
        rs.push_str("}\n");
        Ok(())
    };

    // Emit `NETWORK_CONTRACT`, constant groups, byte-offset packet records, and input string tables.
    group(
        "NETWORK_CONTRACT",
        schema.get("contract").ok_or("missing contract")?,
    )?;
    for (name, values) in schema
        .get("constants")
        .and_then(|v| v.as_object())
        .ok_or("missing constants")?
    {
        group(&name.to_uppercase(), values)?;
    }
    for (name, fields) in schema
        .get("records")
        .and_then(|v| v.as_object())
        .ok_or("missing records")?
    {
        let mut at: usize = 0;
        let mut offsets = Vec::new();
        for (field, width_val) in fields.as_object().ok_or("record must be object")? {
            let width = width_val.as_usize().ok_or("width must be number")?;
            offsets.push((upper_transport(field), JsonValue::Number(at as f64)));
            at += width;
        }
        offsets.push(("BYTES".to_string(), JsonValue::Number(at as f64)));
        group(&name.to_uppercase(), &JsonValue::Object(offsets))?;
    }
    let mut input_catalog = String::from("// Generated by cargo xtask transport-schema; do not edit.\n");
    for (name, key) in [("INPUT_CODES", "inputCodes"), ("INPUT_ACTIONS", "inputActions")] {
        let values = schema.get(key).ok_or("missing input list")?;
        let arr = values.as_array().ok_or("input list must be array")?;
        let items: Vec<String> = arr
            .iter()
            .map(|v| quote_str(v.as_str().unwrap()))
            .collect();
        rs.push_str(&format!(
            "pub const {name}: [&str; {}] = [{}];\n",
            arr.len(),
            items.join(",")
        ));
        if name == "INPUT_CODES" {
            input_catalog.push_str(&format!("pub const INPUT_CODES: [&str; {}] = [{}];\n", arr.len(), items.join(",")));
        }
    }

    // Controls and transport must accept the same physical code vocabulary.
    write_or_check(root, "rust/bfe-interface/src/input_codes.rs", &input_catalog,
        check, "input code catalog needs regeneration")?;
    let path = "rust/bfe-transport/src/layout.rs";
    write_or_check(
        root,
        path,
        &rs,
        check,
        &format!("{path} needs regeneration"),
    )
}

