// Numeric boundary layout generators (`layouts.rs`).
//
// Why this module exists:
// Ports the six Node.js boundary layout generators that emit paired JavaScript
// (`src/.../*layout.js`) and Rust (`rust/.../*layout.rs`) constant modules from JSON
// schema files or inline tables:
// - `presentation_schema` -> ports `tools/presentation-schema.mjs`
// - `environment_schema`  -> ports `tools/environment-schema.mjs`
// - `transport_schema`    -> ports `tools/transport-schema.mjs`
// - `audio_control_schema`-> ports `tools/audio-control-schema.mjs` (`main`)
// - `audio_schema`        -> ports `tools/audio-schema.mjs` (`main`)
// - `audio_codec_schema`  -> ports `tools/audio-codec-schema.mjs` (`main`)
//
// Byte-identical formatting and ordering rules:
// 1. Property order in every emitted `Object.freeze({...})` or `{...}` literal
//    matches V8's `Object.entries` insertion order from the source `.json` file or
//    static table, serialized via `JsonValue::to_json_compact()` (zero spaces after
//    `:` or `,`).
// 2. Identifier case conversion rules differ subtly between scripts and are preserved
//    verbatim:
//    - `upper_camel` (`s.replace(/[A-Z]/g, (c, i) => (i ? '_' : '') + c).toUpperCase()`)
//      inserts `_` before every uppercase letter except at index 0, so consecutive
//      capitals split (e.g. `2D` -> `2_D`). Used by `presentation-schema.mjs` and
//      `environment-schema.mjs`.
//    - `upper_transport` (`s.replace(/([a-z0-9])([A-Z])/g, '$1_$2').toUpperCase()`)
//      only inserts `_` between a lowercase/digit character and an uppercase character.
//      Used by `transport-schema.mjs`.
// 3. Generated header banners keep the historical `// Generated by tools/<name>.mjs; do not edit.`
//    first line and end every file with a single trailing `\n`.

use crate::json::{quote_str, JsonValue};
use std::collections::HashMap;
use std::fs;
use std::path::Path;

// Ports `const upper = s => s.replace(/[A-Z]/g, (c, i) => (i ? '_' : '') + c).toUpperCase()`
// from `tools/presentation-schema.mjs` and `tools/environment-schema.mjs`.
//
// Formatting rule: every ASCII uppercase character at `i > 0` is preceded by `_`,
// even when preceded by another uppercase letter or digit. The lowercase form of
// `upper_camel(name)` is also used for the Rust `pub mod <name>` identifier.
fn upper_camel(s: &str) -> String {
    let mut out = String::new();
    for (i, c) in s.chars().enumerate() {
        if c.is_ascii_uppercase() {
            if i > 0 {
                out.push('_');
            }
            out.push(c);
        } else {
            out.push(c.to_ascii_uppercase());
        }
    }
    out
}

// Ports `const upper = s => s.replace(/([a-z0-9])([A-Z])/g, '$1_$2').toUpperCase()`
// from `tools/transport-schema.mjs`.
//
// Formatting rule: unlike `upper_camel`, an underscore is inserted only when an
// ASCII lowercase letter or digit is immediately followed by an ASCII uppercase
// letter.
fn upper_transport(s: &str) -> String {
    let chars: Vec<char> = s.chars().collect();
    let mut out = String::new();
    for i in 0..chars.len() {
        let c = chars[i];
        out.push(c.to_ascii_uppercase());
        if i + 1 < chars.len() && (c.is_ascii_lowercase() || c.is_ascii_digit()) && chars[i + 1].is_ascii_uppercase() {
            out.push('_');
        }
    }
    out
}

// Writes `expected` to `root/rel_path`, or in `--check` mode verifies that the
// existing file on disk is byte-for-byte identical to `expected` (treating a
// missing file as stale).
pub fn write_or_check(root: &Path, rel_path: &str, expected: &str, check: bool, err_msg: &str) -> Result<(), String> {
    let full = root.join(rel_path);
    if check {
        let have = fs::read_to_string(&full).ok();
        if have.as_deref() != Some(expected) {
            return Err(err_msg.to_string());
        }
    } else {
        if let Some(parent) = full.parent() {
            fs::create_dir_all(parent).map_err(|e| e.to_string())?;
        }
        fs::write(&full, expected).map_err(|e| e.to_string())?;
    }
    Ok(())
}

// Ports `tools/presentation-schema.mjs`.
//
// Why this generator exists:
// Defines one numeric boundary for browser and native hosts across 15 presentation,
// pose, audio-control, and render phases so no renderer or content objects cross the
// WASM boundary. Each `[schema, js_path, rs_path]` entry in `LAYOUTS` regenerates
// independently from `rust/sim/schema/<schema>` (including relative paths into
// `rust/bfe-render/schema/`).
//
// Ordering and formatting rules:
// - `imports`: imported record definitions from `rust/sim/schema/<source.file>` are
//   inserted into `records` before emitting constants, preserving V8 property insertion
//   order.
// - `records`: fields are packed sequentially starting at `at = 0` in exact JSON key
//   order, followed by `STRIDE = at`. JS receives `export const <Name> = Object.freeze({...});`
//   via compact JSON; Rust receives `pub mod <snake_name> { pub const <FIELD>: usize = <val>; }`.
// - `hostWriters`: emits `export function <name>(a,at,<args>)` in JS immediately after
//   `records`, copying raw scalar facts with `NaN` as the absent-value tag.
// - `enums`: variants receive sequential `0..N` ordinals in array order (`u32` in Rust).
// - `limits`: key/value bounds keep JSON key order (`usize` in Rust).
// - `sharedRustLimits`: emits standalone Rust constant files (such as shared detector
//   limits) without introducing a crate dependency on `bfe-presentation`.
pub fn presentation_schema(root: &Path, check: bool) -> Result<(), String> {
    const LAYOUTS: &[(&str, &str, &str)] = &[
        ("../../bfe-render/schema/scene-pose-layout.json", "src/presentation/scene-pose-layout.js", "rust/bfe-presentation/src/scene_pose_layout.rs"),
        ("../../bfe-render/schema/scene-pose-layout.json", "src/rust-render/pose-layout.js", "rust/bfe-render/src/scene_pose_layout.rs"),
        ("../../bfe-render/schema/scene-transform-layout.json", "src/rust-render/scene-transform-layout.js", "rust/bfe-render/src/scene_transform_layout.rs"),
        ("visual-effects-layout.json", "src/presentation/visual-effects-layout.js", "rust/bfe-presentation/src/visual_effects_layout.rs"),
        ("lightning-layout.json", "src/presentation/lightning-layout.js", "rust/bfe-presentation/src/effects/lightning_layout.rs"),
        ("sniper-layout.json", "src/presentation/sniper-layout.js", "rust/bfe-presentation/src/sniper_layout.rs"),
        ("network-layout.json", "src/runtime/network-layout.js", "rust/bfe-presentation/src/network_layout.rs"),
        ("interface-batch-layout.json", "src/interface/batch-layout.js", "rust/bfe-presentation/src/interface_batch_layout.rs"),
        ("shell-music-layout.json", "src/audio/shell-music-layout.js", "rust/audio-control/src/shell_music_layout.rs"),
        ("page-layout.json", "src/presentation/page-layout.js", "rust/bfe-presentation/src/page_layout.rs"),
        ("presentation-layout.json", "src/presentation/layout.js", "rust/bfe-presentation/src/layout.rs"),
        ("ordnance-layout.json", "src/presentation/ordnance-layout.js", "rust/bfe-presentation/src/ordnance_layout.rs"),
        ("timeline-layout.json", "src/presentation/timeline-layout.js", "rust/bfe-pose/src/timeline_layout.rs"),
        ("items-layout.json", "src/presentation/items-layout.js", "rust/bfe-presentation/src/items_layout.rs"),
        ("scene-layout.json", "src/rust-render/scene-layout.js", "rust/bfe-render/src/scene_layout.rs"),
    ];

    for &(schema, js_path, rs_path) in LAYOUTS {
        let schema_path = root.join("rust/sim/schema").join(schema);
        let text = fs::read_to_string(&schema_path).map_err(|e| e.to_string())?;
        let doc = JsonValue::parse(&text)?;
        let version = doc.get("version").and_then(|v| v.as_u32()).ok_or("missing version")?;
        let empty = Vec::new();
        let mut records = doc.get("records").and_then(|v| v.as_object()).map(|s| s.to_vec()).unwrap_or_default();
        let enums = doc.get("enums").and_then(|v| v.as_object()).unwrap_or(&empty);
        let limits = doc.get("limits").and_then(|v| v.as_object()).unwrap_or(&empty);
        let shared_rust_limits = doc.get("sharedRustLimits").and_then(|v| v.as_object()).unwrap_or(&empty);
        let imports = doc.get("imports").and_then(|v| v.as_object()).unwrap_or(&empty);
        let host_writers = doc.get("hostWriters").and_then(|v| v.as_object()).unwrap_or(&empty);

        // Imported source rows keep the pose join tied to the original producer ABI.
        for (name, source) in imports {
            let imp_file = source.get("file").and_then(|v| v.as_str()).ok_or("missing import file")?;
            let imp_rec = source.get("record").and_then(|v| v.as_str()).ok_or("missing import record")?;
            let imp_text = fs::read_to_string(root.join("rust/sim/schema").join(imp_file)).map_err(|e| e.to_string())?;
            let imp_doc = JsonValue::parse(&imp_text)?;
            let rec_val = imp_doc
                .get("records")
                .and_then(|r| r.get(imp_rec))
                .cloned()
                .ok_or_else(|| format!("Unknown imported record {name}"))?;
            if let Some(existing) = records.iter_mut().find(|(k, _)| k == name) {
                existing.1 = rec_val;
            } else {
                records.push((name.clone(), rec_val));
            }
        }

        let mut js = format!("// Generated by tools/presentation-schema.mjs; do not edit.\nexport const VERSION = {version};\n");
        let mut rs = format!("// Generated by tools/presentation-schema.mjs; do not edit.\npub const VERSION: u32 = {version};\n");

        // Packed fields retain schema order: hosts and kernels address the same
        // scalar words, including holes explicitly described as field widths.
        for (name, fields_val) in &records {
            let fields = fields_val.as_object().ok_or("record must be object")?;
            let mut at: usize = 0;
            let mut values = Vec::new();
            for (field, n_val) in fields {
                let n = n_val.as_usize().ok_or("field width must be number")?;
                values.push((upper_camel(field), JsonValue::Number(at as f64)));
                at += n;
            }
            values.push(("STRIDE".to_string(), JsonValue::Number(at as f64)));
            let values_obj = JsonValue::Object(values.clone());
            js.push_str(&format!("export const {name} = Object.freeze({});\n", values_obj.to_json_compact()));
            let mod_name = upper_camel(name).to_lowercase();
            let rs_lines: Vec<String> = values.iter().map(|(k, v)| format!("    pub const {k}: usize = {};", v.as_usize().unwrap())).collect();
            rs.push_str(&format!("pub mod {mod_name} {{\n{}\n}}\n", rs_lines.join("\n")));
        }

        // Host writers only copy raw facts; flags, defaults and identity policy live
        // in the native owner. Optional scalars use NaN as the absent-value tag.
        for (name, spec) in host_writers {
            let rec_name = spec.get("record").and_then(|v| v.as_str()).ok_or("missing hostWriter record")?;
            let fields = records
                .iter()
                .find(|(k, _)| k == rec_name)
                .and_then(|(_, v)| v.as_object())
                .ok_or("missing hostWriter record fields")?;
            let args_arr = spec.get("args").and_then(|v| v.as_array()).ok_or("missing hostWriter args")?;
            let args_str: Vec<&str> = args_arr.iter().filter_map(|v| v.as_str()).collect();
            let spec_fields = spec.get("fields").ok_or("missing hostWriter fields")?;
            let mut offset: usize = 0;
            js.push_str(&format!("export function {name}(a,at,{}){{\n", args_str.join(",")));
            for (field, width_val) in fields {
                let width = width_val.as_usize().ok_or("field width must be number")?;
                let rule = spec_fields.get(field).ok_or_else(|| format!("missing hostWriter field rule {field}"))?;
                let base = if let Some(arg) = rule.get("arg").and_then(|v| v.as_str()) {
                    arg.to_string()
                } else {
                    let path = rule.get("path").and_then(|v| v.as_str()).unwrap_or("undefined");
                    format!("source.{path}")
                };
                let is_presence = rule.get("presence").and_then(|v| v.as_bool()).unwrap_or(false);
                let is_indices = rule.get("indices").and_then(|v| v.as_bool()).unwrap_or(false);
                let components = rule.get("components").and_then(|v| v.as_array());
                for component in 0..width {
                    let value = if is_presence {
                        format!("Number({base}!=null)")
                    } else if is_indices {
                        format!("({base}?.[{component}]??NaN)")
                    } else if let Some(comps) = components {
                        let comp_name = comps.get(component).and_then(|v| v.as_str()).unwrap_or("undefined");
                        format!("({base}?.{comp_name}??NaN)")
                    } else {
                        format!("({base}??NaN)")
                    };
                    js.push_str(&format!(" a[at+{offset}]={value};\n"));
                    offset += 1;
                }
            }
            js.push_str("}\n");
        }

        // Enum order is also ABI: emit the same ordinal for both consumers.
        for (name, names_val) in enums {
            let names = names_val.as_array().ok_or("enum must be array")?;
            let mut values = Vec::new();
            for (i, n_val) in names.iter().enumerate() {
                let n = n_val.as_str().ok_or("enum variant must be string")?;
                values.push((upper_camel(n), JsonValue::Number(i as f64)));
            }
            let values_obj = JsonValue::Object(values.clone());
            js.push_str(&format!("export const {name} = Object.freeze({});\n", values_obj.to_json_compact()));
            let mod_name = upper_camel(name).to_lowercase();
            let rs_lines: Vec<String> = values.iter().map(|(k, v)| format!("    pub const {k}: u32 = {};", v.as_usize().unwrap())).collect();
            rs.push_str(&format!("pub mod {mod_name} {{\n{}\n}}\n", rs_lines.join("\n")));
        }

        // Bounds accompany offsets so registration and fixed scratch agree.
        for (name, values_val) in limits {
            let values = values_val.as_object().ok_or("limit must be object")?;
            let mut fields = Vec::new();
            for (k, v) in values {
                fields.push((upper_camel(k), v.clone()));
            }
            let fields_obj = JsonValue::Object(fields.clone());
            js.push_str(&format!("export const {name} = Object.freeze({});\n", fields_obj.to_json_compact()));
            let mod_name = upper_camel(name).to_lowercase();
            let rs_lines: Vec<String> = fields.iter().map(|(k, v)| format!("    pub const {k}: usize = {};", v.as_usize().unwrap())).collect();
            rs.push_str(&format!("pub mod {mod_name} {{\n{}\n}}\n", rs_lines.join("\n")));
        }

        // Shared detector limits belong to this schema even when a lower-level
        // crate consumes them. Emit a small module without a presentation dependency.
        let mut outputs = vec![(js_path.to_string(), js), (rs_path.to_string(), rs)];
        for (name, path_val) in shared_rust_limits {
            let path = path_val.as_str().ok_or("sharedRustLimits path must be string")?;
            let values = limits
                .iter()
                .find(|(k, _)| k == name)
                .and_then(|(_, v)| v.as_object())
                .ok_or_else(|| format!("Unknown shared limit {name}"))?;
            let lines: Vec<String> = values.iter().map(|(k, v)| format!("pub const {}: usize = {};", upper_camel(k), v.as_usize().unwrap())).collect();
            outputs.push((
                path.to_string(),
                format!("// Generated by tools/presentation-schema.mjs from {schema}; do not edit.\n{}\n", lines.join("\n")),
            ));
        }

        // Check every consumer, including modules outside presentation, so a
        // schema edit cannot leave one crate accepting a different row count.
        for (path, value) in outputs {
            write_or_check(root, &path, &value, check, &format!("{path} needs regeneration"))?;
        }
    }
    Ok(())
}

// Ports `tools/environment-schema.mjs`.
//
// Why this generator exists:
// Generates the numeric boundary of the destruction and weather presentation phase
// (`rust/bfe-environment`) from `rust/bfe-environment/layout.json` into
// `src/environment/layout.js` and `rust/bfe-environment/src/layout.rs`.
//
// Ordering and formatting rules:
// - `resolve(val, strides)` ports `const resolve = (text) => ...`: splits on `*` and
//   multiplies integer literals, `Owner.FIELD` limit lookups (converting `FIELD` from
//   `SCREAMING_SNAKE_CASE` to `camelCase`), or `Owner.STRIDE` record strides.
// - `enums` in `environment-schema.mjs` emit `f64` constants with a `.0` suffix in
//   Rust (`pub const <K>: f64 = <v>.0;`) because environment records store enum tags
//   inside `f64` slices.
// - `blocks` lay out contiguous named slices end-to-end starting at `resolve(block.start)`,
//   advancing by `resolve(count) * resolve(stride)` per entry and terminating with `LEN`.
pub fn environment_schema(root: &Path, check: bool) -> Result<(), String> {
    let layout_path = root.join("rust/bfe-environment/layout.json");
    let text = fs::read_to_string(&layout_path).map_err(|e| e.to_string())?;
    let layout = JsonValue::parse(&text)?;
    let version = layout.get("version").and_then(|v| v.as_u32()).ok_or("missing version")?;
    let empty = Vec::new();
    let records = layout.get("records").and_then(|v| v.as_object()).unwrap_or(&empty);
    let enums = layout.get("enums").and_then(|v| v.as_object()).unwrap_or(&empty);
    let limits = layout.get("limits").and_then(|v| v.as_object()).unwrap_or(&empty);
    let blocks = layout.get("blocks").and_then(|v| v.as_object()).unwrap_or(&empty);

    // Ports `field.toLowerCase().replace(/_(.)/g, (m, c) => c.toUpperCase())`
    // to convert `MAX_PARTICLES` into `maxParticles` when resolving `Limits.FIELD`.
    let to_camel = |s: &str| -> String {
        let lower = s.to_lowercase();
        let mut out = String::new();
        let mut cap = false;
        for c in lower.chars() {
            if c == '_' {
                cap = true;
            } else if cap {
                out.push(c.to_ascii_uppercase());
                cap = false;
            } else {
                out.push(c);
            }
        }
        out
    };

    // Ports `resolve(text)` from `tools/environment-schema.mjs`: evaluates a number,
    // a symbolic reference `Owner.FIELD` / `Owner.STRIDE`, or a `*`-separated product.
    let resolve = |val: &JsonValue, strides: &HashMap<String, usize>| -> Result<usize, String> {
        let text = match val {
            JsonValue::Number(n) => (*n as usize).to_string(),
            JsonValue::String(s) => s.clone(),
            _ => return Err("cannot resolve non-string/number".into()),
        };
        let mut product: usize = 1;
        for raw_token in text.split('*') {
            let token = raw_token.trim();
            if token.chars().all(|c| c.is_ascii_digit()) && !token.is_empty() {
                product *= token.parse::<usize>().unwrap();
                continue;
            }
            let parts: Vec<&str> = token.split('.').collect();
            if parts.len() != 2 {
                return Err(format!("layout.json: cannot resolve {token}"));
            }
            let (owner, field) = (parts[0], parts[1]);
            let camel = to_camel(field);
            let limit_val = limits.iter().find(|(k, _)| k == owner).and_then(|(_, v)| v.get(&camel)).and_then(|v| v.as_usize());
            let resolved = limit_val.or_else(|| if field == "STRIDE" { strides.get(owner).copied() } else { None });
            match resolved {
                Some(v) => product *= v,
                None => return Err(format!("layout.json: cannot resolve {token}")),
            }
        }
        Ok(product)
    };

    let mut strides = HashMap::new();
    let mut js = format!("// Generated by tools/environment-schema.mjs; do not edit.\nexport const VERSION = {version};\n");
    let mut rs = format!("// Generated by tools/environment-schema.mjs; do not edit.\npub const VERSION: u32 = {version};\n");

    // Emit packed record field offsets and record `STRIDE` values for subsequent `blocks` resolution.
    for (name, fields_val) in records {
        let fields = fields_val.as_object().ok_or("record must be object")?;
        let mut at: usize = 0;
        let mut values = Vec::new();
        for (field, n_val) in fields {
            values.push((upper_camel(field), JsonValue::Number(at as f64)));
            at += resolve(n_val, &strides)?;
        }
        values.push(("STRIDE".to_string(), JsonValue::Number(at as f64)));
        strides.insert(name.clone(), at);
        let values_obj = JsonValue::Object(values.clone());
        js.push_str(&format!("export const {name} = Object.freeze({});\n", values_obj.to_json_compact()));
        let mod_name = upper_camel(name).to_lowercase();
        let rs_lines: Vec<String> = values.iter().map(|(k, v)| format!("    pub const {k}: usize = {};", v.as_usize().unwrap())).collect();
        rs.push_str(&format!("pub mod {mod_name} {{\n{}\n}}\n", rs_lines.join("\n")));
    }

    // Emit enum ordinal constants (`f64` with `.0` in Rust, integer properties in JS).
    for (name, names_val) in enums {
        let names = names_val.as_array().ok_or("enum must be array")?;
        let mut values = Vec::new();
        for (i, n_val) in names.iter().enumerate() {
            let n = n_val.as_str().ok_or("enum variant must be string")?;
            values.push((upper_camel(n), JsonValue::Number(i as f64)));
        }
        let values_obj = JsonValue::Object(values.clone());
        js.push_str(&format!("export const {name} = Object.freeze({});\n", values_obj.to_json_compact()));
        let mod_name = upper_camel(name).to_lowercase();
        let rs_lines: Vec<String> = values.iter().map(|(k, v)| format!("    pub const {k}: f64 = {}.0;", v.as_usize().unwrap())).collect();
        rs.push_str(&format!("pub mod {mod_name} {{\n{}\n}}\n", rs_lines.join("\n")));
    }

    // Emit capacity limits shared by the environment WASM kernel and JS caller.
    for (name, values_val) in limits {
        let values = values_val.as_object().ok_or("limit must be object")?;
        let mut fields = Vec::new();
        for (k, v) in values {
            fields.push((upper_camel(k), v.clone()));
        }
        let fields_obj = JsonValue::Object(fields.clone());
        js.push_str(&format!("export const {name} = Object.freeze({});\n", fields_obj.to_json_compact()));
        let mod_name = upper_camel(name).to_lowercase();
        let rs_lines: Vec<String> = fields.iter().map(|(k, v)| format!("    pub const {k}: usize = {};", v.as_usize().unwrap())).collect();
        rs.push_str(&format!("pub mod {mod_name} {{\n{}\n}}\n", rs_lines.join("\n")));
    }

    // Named blocks laid end to end: where each entry starts, and the whole's length
    // (in the units of the strides given).
    for (name, block_val) in blocks {
        let start_val = block_val.get("start").ok_or("block missing start")?;
        let mut at = resolve(start_val, &strides)?;
        let entries = block_val.get("entries").and_then(|v| v.as_array()).ok_or("block missing entries")?;
        let mut values = Vec::new();
        for entry_val in entries {
            let arr = entry_val.as_array().ok_or("block entry must be array")?;
            let entry_name = arr[0].as_str().ok_or("entry name must be string")?;
            values.push((upper_camel(entry_name), JsonValue::Number(at as f64)));
            at += resolve(&arr[1], &strides)? * resolve(&arr[2], &strides)?;
        }
        values.push(("LEN".to_string(), JsonValue::Number(at as f64)));
        let values_obj = JsonValue::Object(values.clone());
        js.push_str(&format!("export const {name} = Object.freeze({});\n", values_obj.to_json_compact()));
        let mod_name = upper_camel(name).to_lowercase();
        let rs_lines: Vec<String> = values.iter().map(|(k, v)| format!("    pub const {k}: usize = {};", v.as_usize().unwrap())).collect();
        rs.push_str(&format!("pub mod {mod_name} {{\n{}\n}}\n", rs_lines.join("\n")));
    }

    for (path, value) in [("src/environment/layout.js", &js), ("rust/bfe-environment/src/layout.rs", &rs)] {
        write_or_check(root, path, value, check, &format!("{path} needs regeneration: node tools/environment-schema.mjs"))?;
    }
    Ok(())
}

// Ports `tools/transport-schema.mjs`.
//
// Why this generator exists:
// BFE-UDP/1 wire constants, byte-width packet records, and gameplay input names
// share a single source (`rust/sim/schema/transport-layout.json`) for both the JS
// host (`src/net/layout.js`) and `rust/bfe-transport/src/layout.rs`.
//
// Ordering and formatting rules:
// - `group(name, values)` emits `export const <NAME> = Object.freeze(<compact JSON>);`
//   in JS (preserving camelCase keys in `NETWORK_CONTRACT` and `constants`, and
//   `upper_transport` keys plus `BYTES` in `records`), and `pub mod <lower>` in Rust.
// - Rust constant types follow `typeof value === 'string' ? '&str' : value > 0xffffffff ? 'u64' : 'usize'`.
// - `INPUT_CODES` and `INPUT_ACTIONS` emit fixed-size `[&str; N]` arrays in Rust
//   with comma-separated quoted strings and no spaces after commas (`items.join(",")`).
pub fn transport_schema(root: &Path, check: bool) -> Result<(), String> {
    let schema_path = root.join("rust/sim/schema/transport-layout.json");
    let text = fs::read_to_string(&schema_path).map_err(|e| e.to_string())?;
    let schema = JsonValue::parse(&text)?;
    let version = schema.get("version").and_then(|v| v.as_usize()).ok_or("missing version")?;

    let mut js = format!("// Generated by tools/transport-schema.mjs; do not edit.\nexport const TRANSPORT_VERSION = {version};\n");
    let mut rs = format!("// Generated by tools/transport-schema.mjs; do not edit.\npub const VERSION: usize = {version};\n");

    // Ports `const group = (name, values) => ...` from `tools/transport-schema.mjs`.
    let mut group = |name: &str, values: &JsonValue| -> Result<(), String> {
        js.push_str(&format!("export const {name} = Object.freeze({});\n", values.to_json_compact()));
        rs.push_str(&format!("pub mod {} {{\n", name.to_lowercase()));
        for (key, value) in values.as_object().ok_or("group values must be object")? {
            let ty = match value {
                JsonValue::String(_) => "&str",
                JsonValue::Number(n) if *n > 0xffff_ffffu64 as f64 => "u64",
                _ => "usize",
            };
            rs.push_str(&format!("    pub const {}: {ty} = {};\n", upper_transport(key), value.to_json_compact()));
        }
        rs.push_str("}\n");
        Ok(())
    };

    // Emit `NETWORK_CONTRACT`, constant groups, byte-offset packet records, and input string tables.
    group("NETWORK_CONTRACT", schema.get("contract").ok_or("missing contract")?)?;
    for (name, values) in schema.get("constants").and_then(|v| v.as_object()).ok_or("missing constants")? {
        group(&name.to_uppercase(), values)?;
    }
    for (name, fields) in schema.get("records").and_then(|v| v.as_object()).ok_or("missing records")? {
        let mut at: usize = 0;
        let mut offsets = Vec::new();
        for (field, width_val) in fields.as_object().ok_or("record must be object")? {
            let width = width_val.as_usize().ok_or("width must be number")?;
            offsets.push((upper_transport(field), JsonValue::Number(at as f64)));
            at += width;
        }
        offsets.push(("BYTES".to_string(), JsonValue::Number(at as f64)));
        group(&name.to_uppercase(), &JsonValue::Object(offsets))?;
    }
    for (name, key) in [("INPUT_CODES", "inputCodes"), ("INPUT_ACTIONS", "inputActions")] {
        let values = schema.get(key).ok_or("missing input list")?;
        let arr = values.as_array().ok_or("input list must be array")?;
        js.push_str(&format!("export const {name} = Object.freeze({});\n", values.to_json_compact()));
        let items: Vec<String> = arr.iter().map(|v| quote_str(v.as_str().unwrap())).collect();
        rs.push_str(&format!("pub const {name}: [&str; {}] = [{}];\n", arr.len(), items.join(",")));
    }

    for (path, content) in [("src/net/layout.js", &js), ("rust/bfe-transport/src/layout.rs", &rs)] {
        write_or_check(root, path, content, check, &format!("{path} needs regeneration"))?;
    }
    Ok(())
}

