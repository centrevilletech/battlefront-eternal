// Ports `main(args)` from `tools/audio-schema.mjs`.
//
// Why this generator exists:
// First runs `audio_control_schema` (matching `controlSchema(args)` in `tools/audio-schema.mjs`),
// then emits the wire layout for the page's batched audio commands (`src/audio/commands.js`)
// and the Rust audio mixer's command parser (`rust/audio/src/commands.rs`), including
// `pub fn arity(op: u32) -> usize` computed from the space-separated parameter list.
pub fn audio_schema(root: &Path, check: bool) -> Result<(), String> {
    audio_control_schema(root, check)?;
    const COMMANDS: &[(&str, &str)] = &[
        ("START", "slot sample offset loop rate cutoff at"),
        ("GAIN_SET", "slot value at"),
        ("GAIN", "slot value tau at"),
        ("RATE", "slot value tau at"),
        ("CUTOFF", "slot value tau at"),
        ("SEND", "slot value tau at"),
        ("RELEASE", "slot tau after at"),
        ("STOP", "slot"),
        ("SIDE_SET", "slot side value at"),
        ("SIDE", "slot side value tau at"),
        ("CANCEL", "slot side at"),
        ("STOP_AT", "slot at"),
        ("PLACE", "slot x y z level at"),
        ("POSITION", "slot axis value tau at set"),
        ("PAN", "slot value tau at"),
        ("STREAM_PLACE", "slot x y z level at"),
        ("STREAM_GAIN", "slot value tau at set"),
        ("STREAM_START", "slot part sample when offset pitch loop"),
        ("STREAM_STOP", "slot part at"),
        ("STREAM_RELEASE", "slot"),
        ("STREAM_BIND", "slot channels kind spatial"),
        ("BIND", "slot spatial"),
        ("STREAM_PARAM", "slot kind value tau at"),
        ("FRONT_START", "slot generation when offset pitch loop gain bus"),
        ("FRONT_FADE", "slot start end"),
        ("FRONT_STOP", "slot at"),
        ("FRONT_VOLUME", "master music fx"),
        ("FRONT_DIP", "value seconds at"),
    ];
    let banner = "// Generated by tools/audio-schema.mjs; do not edit.\n";
    let front_entries = vec![
        ("SLOTS".to_string(), JsonValue::Number(64.0)),
        ("END_STRIDE".to_string(), JsonValue::Number(2.0)),
        ("END_SLOT".to_string(), JsonValue::Number(0.0)),
        ("END_GENERATION".to_string(), JsonValue::Number(1.0)),
    ];
    let front_json = JsonValue::Object(front_entries.clone()).to_json_compact();
    let voice_lines: Vec<String> = COMMANDS.iter().enumerate().map(|(i, &(name, fields))| format!("  {name}: {}, // {fields}", i + 1)).collect();
    let js = format!("{banner}export const FRONT = {front_json};\nexport const VOICE = {{\n{}\n}};\n", voice_lines.join("\n"));

    let front_rs: Vec<String> = front_entries.iter().map(|(name, value)| format!("pub const FRONT_{name}: usize = {};", value.as_usize().unwrap())).collect();
    let cmd_rs: Vec<String> = COMMANDS.iter().enumerate().map(|(i, &(name, fields))| format!("pub const {name}: u32 = {}; // {fields}", i + 1)).collect();
    let arity_rs: Vec<String> = COMMANDS.iter().map(|&(name, fields)| format!("    {name} => {},", fields.split(' ').count())).collect();
    let rust = format!(
        "{banner}{}\n{}\npub fn arity(op: u32) -> usize {{ match op {{\n{}\n    _ => 0,\n}} }}\n",
        front_rs.join("\n"),
        cmd_rs.join("\n"),
        arity_rs.join("\n")
    );

    for (path, text) in [("src/audio/commands.js", &js), ("rust/audio/src/commands.rs", &rust)] {
        write_or_check(root, path, text, check, &format!("stale audio command layout: {path}"))?;
    }
    Ok(())
}

// Ports `main(check)` from `tools/audio-codec-schema.mjs`.
//
// Why this generator exists:
// The loading worker (`src/audio/codec-layout.js`) and WASM audio decoder
// (`rust/audio-decode/src/layout.rs`) share one status, metadata-header, format-tag,
// and chunk-limit ABI. The 6-line explanatory banner is emitted at the top of both
// generated files so ownership and units stay beside both views of the ABI.
pub fn audio_codec_schema(root: &Path, check: bool) -> Result<(), String> {
    const LAYOUT: &[(&str, usize)] = &[
        ("NEED_INPUT", 0), ("METADATA", 1), ("OUTPUT", 2), ("DONE", 3), ("ERROR", 4),
        ("SOURCE_RATE", 0), ("RATE", 1), ("CHANNELS", 2), ("BITS", 3), ("FRAMES", 4),
        ("FORMAT", 5), ("OUTPUT_FRAMES", 6), ("LENGTH", 7), ("FLAC", 1), ("OPUS", 2),
        ("WAV", 3), ("INPUT_CHUNK", 65536), ("PCM_CHUNK", 4096),
    ];
    // Keep ownership and units beside both generated views of this ABI.
    // Numeric values are shared; the worker must not invent local offsets.
    let banner = "// Generated by tools/audio-codec-schema.mjs; do not edit.\n\
// One loading-worker job owns each handle; these are not shared-memory cells.\n\
// Step statuses select bytes needed, metadata, planar PCM, completion or error.\n\
// SOURCE_RATE is codec PCM Hz; RATE and FRAMES describe delivered PCM.\n\
// OUTPUT_FRAMES is this transfer's per-lane stride, not the track length.\n\
// Chunk limits bound transfers independently of compressed asset duration.\n";
    let entries: Vec<(String, JsonValue)> = LAYOUT.iter().map(|&(k, v)| (k.to_string(), JsonValue::Number(v as f64))).collect();
    let js = format!("{banner}export const CODEC = {};\n", JsonValue::Object(entries).to_json_compact());
    let rs_lines: Vec<String> = LAYOUT.iter().map(|&(k, v)| format!("pub const {k}: usize = {v};")).collect();
    let rs = format!("{banner}{}\n", rs_lines.join("\n"));

    for (path, text) in [("src/audio/codec-layout.js", &js), ("rust/audio-decode/src/layout.rs", &rs)] {
        write_or_check(root, path, text, check, &format!("stale codec layout: {path}"))?;
    }
    Ok(())
}
