// First runs `audio_control_schema`, then emits the wire layout for the Rust
// audio mixer's command parser (`rust/audio/src/commands.rs`), including
// `pub fn arity(op: u32) -> usize` computed from the space-separated parameter list.
pub fn audio_schema(root: &Path, check: bool) -> Result<(), String> {
    audio_control_schema(root, check)?;
    const COMMANDS: &[(&str, &str)] = &[
        ("START", "slot sample offset loop rate cutoff at"),
        ("GAIN_SET", "slot value at"),
        ("GAIN", "slot value tau at"),
        ("RATE", "slot value tau at"),
        ("CUTOFF", "slot value tau at"),
        ("SEND", "slot value tau at"),
        ("RELEASE", "slot tau after at"),
        ("STOP", "slot"),
        ("SIDE_SET", "slot side value at"),
        ("SIDE", "slot side value tau at"),
        ("CANCEL", "slot side at"),
        ("STOP_AT", "slot at"),
        ("PLACE", "slot x y z level at"),
        ("POSITION", "slot axis value tau at set"),
        ("PAN", "slot value tau at"),
        ("STREAM_PLACE", "slot x y z level at"),
        ("STREAM_GAIN", "slot value tau at set"),
        ("STREAM_START", "slot part sample when offset pitch loop"),
        ("STREAM_STOP", "slot part at"),
        ("STREAM_RELEASE", "slot"),
        ("STREAM_BIND", "slot channels kind spatial"),
        ("BIND", "slot spatial"),
        ("STREAM_PARAM", "slot kind value tau at"),
        ("FRONT_START", "slot generation when offset pitch loop gain bus"),
        ("FRONT_FADE", "slot start end"),
        ("FRONT_STOP", "slot at"),
        ("FRONT_VOLUME", "master music fx"),
        ("FRONT_DIP", "value seconds at"),
    ];
    let banner = "// Generated by tools/audio-schema.mjs; do not edit.\n";
    let front_entries = [
        ("SLOTS", 64usize),
        ("END_STRIDE", 2usize),
        ("END_SLOT", 0usize),
        ("END_GENERATION", 1usize),
    ];

    let front_rs: Vec<String> = front_entries
        .iter()
        .map(|(name, value)| format!("pub const FRONT_{name}: usize = {value};"))
        .collect();
    let cmd_rs: Vec<String> = COMMANDS
        .iter()
        .enumerate()
        .map(|(i, &(name, fields))| format!("pub const {name}: u32 = {}; // {fields}", i + 1))
        .collect();
    let arity_rs: Vec<String> = COMMANDS
        .iter()
        .map(|&(name, fields)| format!("    {name} => {},", fields.split(' ').count()))
        .collect();
    let rust = format!(
        "{banner}{}\n{}\npub fn arity(op: u32) -> usize {{ match op {{\n{}\n    _ => 0,\n}} }}\n",
        front_rs.join("\n"),
        cmd_rs.join("\n"),
        arity_rs.join("\n")
    );

    let path = "rust/audio/src/commands.rs";
    write_or_check(
        root,
        path,
        &rust,
        check,
        &format!("stale audio command layout: {path}"),
    )
}

