// Ports tools/host-contract.mjs.
//
// Computes the SHA-256 wire compatibility fingerprint of the simulation host
// boundary and writes or checks src/sim/host-schema.js.
//
// Why these exact inputs are hashed:
// - tools/sim-schema.mjs: the schema compiler specification.
// - rust/sim/schema/**: the declarative entity store and command/event schemas.
// - src/sim/gen/**: the generated JavaScript mirror, sync, and table modules.
//
// Byte-identity rules matching tools/host-contract.mjs:
// 1. Directory traversal (`files`) returns relative paths from the repository
//    root using forward slashes (`/`), sorted in lexicographical code-unit
//    order (`Array.prototype.sort()`).
// 2. `digest` sorts the combined path list again, then feeds each file into a
//    single SHA-256 state framed as `<normalized-path>\0<byte-length>\0`
//    followed by the raw file bytes. Doing length-prefixed framing prevents
//    boundary ambiguity between adjacent files.
// 3. The output file `src/sim/host-schema.js` is two lines ending in `\n`:
//    the generator banner and `export const HOST_SCHEMA = "<64-char hex>";`.

use crate::json::quote_str;
use crate::layouts::write_or_check;
use sha2::{Digest, Sha256};
use std::fs;
use std::path::Path;

// Ports `files(root, directory)` in tools/host-contract.mjs.
// Recursively collects every file below `directory`, returning paths relative
// to `root` with `/` separators sorted in lexicographical order.
pub fn files(root: &Path, directory: &str) -> Result<Vec<String>, String> {
    let mut out = Vec::new();
    let dir_path = root.join(directory);
    if !dir_path.exists() {
        return Ok(out);
    }
    let mut entries: Vec<_> = fs::read_dir(&dir_path)
        .map_err(|e| e.to_string())?
        .filter_map(|e| e.ok())
        .collect();
    entries.sort_by_key(|e| e.file_name());
    for entry in entries {
        let name = entry
            .file_name()
            .into_string()
            .map_err(|_| "non-utf8 filename")?;
        let rel = format!("{directory}/{name}");
        if entry.file_type().map_err(|e| e.to_string())?.is_dir() {
            out.extend(files(root, &rel)?);
        } else {
            out.push(rel);
        }
    }
    out.sort();
    Ok(out)
}

// Ports `digest(root, paths)` in tools/host-contract.mjs.
// Sorts `paths` and hashes `<path>\0<byte_len>\0<raw_bytes>` for each entry.
pub fn digest(root: &Path, mut paths: Vec<String>) -> Result<String, String> {
    paths.sort();
    let mut hasher = Sha256::new();
    for path in paths {
        let bytes = fs::read(root.join(&path)).map_err(|e| format!("{path}: {e}"))?;
        let normalized = path.replace('\\', "/");
        hasher.update(format!("{normalized}\0{}\0", bytes.len()).as_bytes());
        hasher.update(&bytes);
    }
    Ok(format!("{:x}", hasher.finalize()))
}

// Ports `schemaFingerprint(root)` in tools/host-contract.mjs.
// Combines tools/sim-schema.mjs (when present), rust/sim/schema/**, and
// src/sim/gen/** into one SHA-256 hex digest.
pub fn schema_fingerprint(root: &Path) -> Result<String, String> {
    let mut paths = Vec::new();
    if root.join("tools/sim-schema.mjs").exists() {
        paths.push("tools/sim-schema.mjs".to_string());
    }
    paths.extend(files(root, "rust/sim/schema")?);
    paths.extend(files(root, "src/sim/gen")?);
    digest(root, paths)
}

// Ports `generate(check)` in tools/host-contract.mjs.
// Writes `src/sim/host-schema.js` or verifies that the committed file matches.
// Once `tools/host-contract.mjs` and `src/sim/host-schema.js` are removed during
// the deletion sweep, `host_contract` becomes a clean no-op in `--check` mode.
pub fn host_contract(root: &Path, check: bool) -> Result<(), String> {
    if check
        && !root.join("src/sim/host-schema.js").exists()
        && !root.join("tools/host-contract.mjs").exists()
    {
        return Ok(());
    }
    let fp = schema_fingerprint(root)?;
    let content = format!(
        "// Generated by tools/host-contract.mjs; do not edit.\nexport const HOST_SCHEMA = {};\n",
        quote_str(&fp)
    );
    write_or_check(
        root,
        "src/sim/host-schema.js",
        &content,
        check,
        "Host boundary fingerprint is stale",
    )
}
