// The loading worker and decoder share one metadata/status layout.
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
export function main(check = false) {
  const layout = { NEED_INPUT: 0, METADATA: 1, OUTPUT: 2, DONE: 3, ERROR: 4,
    SOURCE_RATE: 0, RATE: 1, CHANNELS: 2, BITS: 3, FRAMES: 4, FORMAT: 5, OUTPUT_FRAMES: 6, LENGTH: 7, FLAC: 1, OPUS: 2, WAV: 3, INPUT_CHUNK: 65536, PCM_CHUNK: 4096 };
  // Keep ownership and units beside both generated views of this ABI.
  // Numeric values are shared; the worker must not invent local offsets.
  const banner = "// Generated by tools/audio-codec-schema.mjs; do not edit.\n"
    + "// One loading-worker job owns each handle; these are not shared-memory cells.\n"
    + "// Step statuses select bytes needed, metadata, planar PCM, completion or error.\n"
    + "// SOURCE_RATE is codec PCM Hz; RATE and FRAMES describe delivered PCM.\n"
    + "// OUTPUT_FRAMES is this transfer's per-lane stride, not the track length.\n"
    + "// Chunk limits bound transfers independently of compressed asset duration.\n";
  const outputs = [
    ["src/audio/codec-layout.js", banner + "export const CODEC = " + JSON.stringify(layout) + ";\n"],
    ["rust/audio-decode/src/layout.rs", banner + Object.entries(layout).map(([key, value]) => `pub const ${key}: usize = ${value};`).join("\n") + "\n"],
  ];
  for (const [path, text] of outputs) {
    const url = new URL("../" + path, import.meta.url);
    if (check) { if (readFileSync(url, "utf8") !== text) throw Error(`stale codec layout: ${path}`); }
    else writeFileSync(url, text);
  }
}
if (process.argv[1] === fileURLToPath(import.meta.url)) main(process.argv.includes("--check"));
