// One wire layout for the page's batched audio commands and Rust's parser.
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { main as controlSchema } from "./audio-control-schema.mjs";
export const commands = [
  ["START", "slot sample offset loop rate cutoff at"], ["GAIN_SET", "slot value at"],
  ["GAIN", "slot value tau at"], ["RATE", "slot value tau at"], ["CUTOFF", "slot value tau at"],
  ["SEND", "slot value tau at"], ["RELEASE", "slot tau after at"], ["STOP", "slot"],
  ["SIDE_SET", "slot side value at"], ["SIDE", "slot side value tau at"], ["CANCEL", "slot side at"],
  ["STOP_AT", "slot at"], ["PLACE", "slot x y z level at"],
  ["POSITION", "slot axis value tau at set"], ["PAN", "slot value tau at"],
  ["STREAM_PLACE", "slot x y z level at"], ["STREAM_GAIN", "slot value tau at set"],
  ["STREAM_START", "slot part sample when offset pitch loop"], ["STREAM_STOP", "slot part at"],
  ["STREAM_RELEASE", "slot"], ["STREAM_BIND", "slot channels kind spatial"],
  ["BIND", "slot spatial"], ["STREAM_PARAM", "slot kind value tau at"],
  ["FRONT_START", "slot generation when offset pitch loop gain bus"],
  ["FRONT_FADE", "slot start end"], ["FRONT_STOP", "slot at"],
  ["FRONT_VOLUME", "master music fx"], ["FRONT_DIP", "value seconds at"],
];
export function main(args = []) {
  controlSchema(args);
  const banner = "// Generated by tools/audio-schema.mjs; do not edit.\n";
  const front = { SLOTS: 64, END_STRIDE: 2, END_SLOT: 0, END_GENERATION: 1 };
  const js = banner + "export const FRONT = " + JSON.stringify(front) + ";\nexport const VOICE = {\n" + commands.map(([name, fields], i) => `  ${name}: ${i + 1}, // ${fields}`).join("\n") + "\n};\n";
  const rust = banner + Object.entries(front).map(([name, value]) => `pub const FRONT_${name}: usize = ${value};`).join("\n") + "\n" + commands.map(([name, fields], i) => `pub const ${name}: u32 = ${i + 1}; // ${fields}`).join("\n") + "\npub fn arity(op: u32) -> usize { match op {\n" + commands.map(([name, fields]) => `    ${name} => ${fields.split(" ").length},`).join("\n") + "\n    _ => 0,\n} }\n";
  for (const [path, text] of [["src/audio/commands.js", js], ["rust/audio/src/commands.rs", rust]]) {
    const url = new URL("../" + path, import.meta.url);
    if (args.includes("--check")) { if (readFileSync(url, "utf8") !== text) throw new Error(`stale audio command layout: ${path}`); }
    else writeFileSync(url, text);
  }
}
if (process.argv[1] === fileURLToPath(import.meta.url)) main(process.argv.slice(2));
