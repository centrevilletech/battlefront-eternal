// Semantic view facts and native operation traces share one declared boundary.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
const root = fileURLToPath(new URL('../', import.meta.url));
const constant = name => name.replace(/[A-Z]/g, c => '_' + c).toUpperCase();
export function generate(check = false) {
  const schema = JSON.parse(readFileSync(root + 'rust/bfe-render/frame-layout.json'));
  if (schema.version !== 1) throw Error('Unsupported frame layout');
  const fields = rows => {
    let at = 0; const result = {};
    for (const [name, count] of rows) { result[constant(name)] = at; at += count; }
    result.LEN = at; return result;
  };
  const enumerate = rows => Object.fromEntries(rows.map((name, i) => [constant(name), i]));
  const modules = { facts: fields(schema.facts), state: fields(schema.state), binding: fields(schema.binding), command: fields(schema.command), meta: fields(schema.meta), line: fields(schema.line), stats: fields(schema.stats), ui:fields(schema.uiStages), ui_capacity:Object.fromEntries(schema.uiStages.map(([k,v])=>[constant(k),v])), kind: enumerate(schema.kinds), operation: enumerate(schema.operations), role: { ...enumerate(schema.roles), COUNT: schema.roles.length }, limit: Object.fromEntries(Object.entries(schema.limits).map(([k,v]) => [constant(k),v])) };
  const notice = '// Generated by tools/render-frame-layout.mjs; edit frame-layout.json instead.\n';
  const outputs = {
    'src/rust-render/frame-layout.js': notice + Object.entries(modules).map(([k,v]) => `export const ${k.toUpperCase()} = ${JSON.stringify(v)};\n`).join(''),
    'rust/bfe-render/src/frame_layout.rs': notice + Object.entries(modules).map(([k,v]) => `pub mod ${k} {\n` + Object.entries(v).map(([n,x]) => `    pub const ${n}: usize = ${x};`).join('\n') + '\n}\n').join(''),
  };
  for (const [path, text] of Object.entries(outputs)) {
    if (check) { if (readFileSync(root + path, 'utf8') !== text) throw Error('Stale ' + path); }
    else writeFileSync(root + path, text);
  }
}
