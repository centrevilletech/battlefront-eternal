// One numeric boundary for browser and native hosts. No renderer or content
// objects cross it. Regeneration is also checked by the WASM builder.
import {readFileSync,writeFileSync} from 'node:fs';

const upper=s=>s.replace(/[A-Z]/g,(c,i)=>(i?'_':'')+c).toUpperCase();
// One layout file per phase, so presentation, timeline, ordnance and item records
// regenerate independently: [schema, page module, Rust module].
const LAYOUTS=[
 ['visual-effects-layout.json','src/presentation/visual-effects-layout.js','rust/bfe-presentation/src/visual_effects_layout.rs'],
 ['lightning-layout.json','src/presentation/lightning-layout.js','rust/bfe-presentation/src/effects/lightning_layout.rs'],
 ['sniper-layout.json','src/presentation/sniper-layout.js','rust/bfe-presentation/src/sniper_layout.rs'],
 ['network-layout.json','src/runtime/network-layout.js','rust/bfe-presentation/src/network_layout.rs'],
 ['interface-batch-layout.json','src/interface/batch-layout.js','rust/bfe-presentation/src/interface_batch_layout.rs'],
 ['shell-music-layout.json','src/audio/shell-music-layout.js','rust/audio-control/src/shell_music_layout.rs'],
 ['page-layout.json','src/presentation/page-layout.js','rust/bfe-presentation/src/page_layout.rs'],
 ['presentation-layout.json','src/presentation/layout.js','rust/bfe-presentation/src/layout.rs'],
 ['ordnance-layout.json','src/presentation/ordnance-layout.js','rust/bfe-presentation/src/ordnance_layout.rs'],
 ['timeline-layout.json','src/presentation/timeline-layout.js','rust/bfe-pose/src/timeline_layout.rs'],
 ['items-layout.json','src/presentation/items-layout.js','rust/bfe-presentation/src/items_layout.rs'],
 ['scene-layout.json','src/rust-render/scene-layout.js','rust/bfe-render/src/scene_layout.rs'],
];
for(const [schema,jsPath,rsPath] of LAYOUTS) {
const {version, records = {}, enums = {}, limits = {}, sharedRustLimits = {}, hostWriters = {}} = JSON.parse(readFileSync(new URL('../rust/sim/schema/'+schema, import.meta.url), 'utf8'));
let js=`// Generated by tools/presentation-schema.mjs; do not edit.\nexport const VERSION = ${version};\n`;
let rs=`// Generated by tools/presentation-schema.mjs; do not edit.\npub const VERSION: u32 = ${version};\n`;
// Packed fields retain schema order: hosts and kernels address the same
// scalar words, including holes explicitly described as field widths.
for(const [name,fields] of Object.entries(records)) {
 let at=0; const values={};
 for(const [field,n] of Object.entries(fields)) {values[upper(field)]=at;at+=n;}
 values.STRIDE=at;
 js+=`export const ${name} = Object.freeze(${JSON.stringify(values)});\n`;
 rs+=`pub mod ${upper(name).toLowerCase()} {\n${Object.entries(values).map(([k,v])=>`    pub const ${k}: usize = ${v};`).join('\n')}\n}\n`;
}
// Host writers only copy raw facts; flags, defaults and identity policy live
// in the native owner. Optional scalars use NaN as the absent-value tag.
for(const [name,spec]of Object.entries(hostWriters)) {
 const fields=records[spec.record];let offset=0;
 js+=`export function ${name}(a,at,${spec.args.join(',')}){\n`;
 for(const [field,width]of Object.entries(fields)) {
  const rule=spec.fields[field],base=rule.arg||`source.${rule.path}`;
  for(let component=0;component<width;component++) {
   const value=rule.presence?`Number(${base}!=null)`:rule.indices?`(${base}?.[${component}]??NaN)`:rule.components?`(${base}?.${rule.components[component]}??NaN)`:`(${base}??NaN)`;
   js+=` a[at+${offset++}]=${value};\n`;
  }
 }
 js+='}\n';
}
// Enum order is also ABI: emit the same ordinal for both consumers.
for(const [name,names] of Object.entries(enums)) {
 const values=Object.fromEntries(names.map((n,i)=>[upper(n),i]));
 js+=`export const ${name} = Object.freeze(${JSON.stringify(values)});\n`;
 rs+=`pub mod ${upper(name).toLowerCase()} {\n${Object.entries(values).map(([k,v])=>`    pub const ${k}: u32 = ${v};`).join('\n')}\n}\n`;
}
// Bounds accompany offsets so registration and fixed scratch agree.
for(const [name,values] of Object.entries(limits)) {
 const fields=Object.fromEntries(Object.entries(values).map(([k,v])=>[upper(k),v]));
 js+=`export const ${name} = Object.freeze(${JSON.stringify(fields)});\n`;
 rs+=`pub mod ${upper(name).toLowerCase()} {\n${Object.entries(fields).map(([k,v])=>`    pub const ${k}: usize = ${v};`).join('\n')}\n}\n`;
}
// Shared detector limits belong to this schema even when a lower-level
// crate consumes them. Emit a small module without a presentation dependency.
const outputs=[[jsPath,js],[rsPath,rs]];
for(const [name,path] of Object.entries(sharedRustLimits)) {
 const values=limits[name];if(!values)throw Error('Unknown shared limit '+name);
 outputs.push([path,`// Generated by tools/presentation-schema.mjs from ${schema}; do not edit.\n`+
  Object.entries(values).map(([k,v])=>`pub const ${upper(k)}: usize = ${v};`).join('\n')+'\n']);
}
// Check every consumer, including modules outside presentation, so a
// schema edit cannot leave one crate accepting a different row count.
for(const [path,value] of outputs) {
 const url=new URL('../'+path,import.meta.url);
 if(process.argv.includes('--check')) {if(readFileSync(url,'utf8')!==value)throw Error(path+' needs regeneration');}
 else writeFileSync(url,value);
}
}
