// One numeric boundary for browser and native hosts. No renderer or content
// objects cross it. Regeneration is also checked by the WASM builder.
import {readFileSync,writeFileSync} from 'node:fs';

const upper=s=>s.replace(/[A-Z]/g,(c,i)=>(i?'_':'')+c).toUpperCase();
// One layout file per phase, so effect, unit, ordnance and item records
// regenerate independently: [schema, page module, Rust module].
const LAYOUTS=[
 ['presentation-layout.json','src/presentation/layout.js','rust/bfe-presentation/src/layout.rs'],
 ['ordnance-layout.json','src/presentation/ordnance-layout.js','rust/bfe-presentation/src/ordnance_layout.rs'],
 ['items-layout.json','src/presentation/items-layout.js','rust/bfe-presentation/src/items_layout.rs'],
];
for(const [schema,jsPath,rsPath] of LAYOUTS) {
const {version, records = {}, enums = {}, limits = {}} = JSON.parse(readFileSync(new URL('../rust/sim/schema/'+schema, import.meta.url), 'utf8'));
let js=`// Generated by tools/presentation-schema.mjs; do not edit.\nexport const VERSION = ${version};\n`;
let rs=`// Generated by tools/presentation-schema.mjs; do not edit.\npub const VERSION: u32 = ${version};\n`;
for(const [name,fields] of Object.entries(records)) {
 let at=0; const values={};
 for(const [field,n] of Object.entries(fields)) {values[upper(field)]=at;at+=n;}
 values.STRIDE=at;
 js+=`export const ${name} = Object.freeze(${JSON.stringify(values)});\n`;
 rs+=`pub mod ${upper(name).toLowerCase()} {\n${Object.entries(values).map(([k,v])=>`    pub const ${k}: usize = ${v};`).join('\n')}\n}\n`;
}
for(const [name,names] of Object.entries(enums)) {
 const values=Object.fromEntries(names.map((n,i)=>[upper(n),i]));
 js+=`export const ${name} = Object.freeze(${JSON.stringify(values)});\n`;
 rs+=`pub mod ${upper(name).toLowerCase()} {\n${Object.entries(values).map(([k,v])=>`    pub const ${k}: u32 = ${v};`).join('\n')}\n}\n`;
}
for(const [name,values] of Object.entries(limits)) {
 const fields=Object.fromEntries(Object.entries(values).map(([k,v])=>[upper(k),v]));
 js+=`export const ${name} = Object.freeze(${JSON.stringify(fields)});\n`;
 rs+=`pub mod ${upper(name).toLowerCase()} {\n${Object.entries(fields).map(([k,v])=>`    pub const ${k}: usize = ${v};`).join('\n')}\n}\n`;
}
for(const [path,value] of [[jsPath,js],[rsPath,rs]]) {
 const url=new URL('../'+path,import.meta.url);
 if(process.argv.includes('--check')) {if(readFileSync(url,'utf8')!==value)throw Error(path+' needs regeneration');}
 else writeFileSync(url,value);
}
}
