// Emit the browser fallback and Rust registry from the renderer's source manifests.
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { createHash } from 'node:crypto';
const root = fileURLToPath(new URL('../', import.meta.url));
export function generate(check = false) {
  const base = root + 'rust/bfe-render/shaders/';
  const sources = {}, rows = [];
  for (const family of readdirSync(base).sort()) {
    const manifest = JSON.parse(readFileSync(base + family + '/manifest.json'));
    if (manifest.version !== 1) throw Error('Unsupported shader manifest');
    for (const p of manifest.programs) {
      if (!p.key.startsWith(family + '/') || sources[p.key]) throw Error('Invalid shader key ' + p.key);
      const vertex = readFileSync(base + family + '/' + p.vertex, 'utf8');
      const fragment = readFileSync(base + family + '/' + p.fragment, 'utf8');
      if (/#[ \t]*include|#[ \t]*version/.test(vertex + fragment)) throw Error('Source must be self contained');
      const attributes = Object.entries(p.attributes);
      const uniforms = Object.entries(p.uniforms).map(([name, type]) => ({ name, type }));
      const hash = createHash('sha256').update(JSON.stringify({ vertex, fragment, attributes, uniforms })).digest('hex');
      sources[p.key] = { vertex, fragment, attributes, uniforms, hash };
      const pairs = (xs) => xs.map(([n,v]) => `(${JSON.stringify(n)}, ${v})`).join(', ');
      rows.push(`    Spec { key: ${JSON.stringify(p.key)}, vertex: include_str!("../shaders/${family}/${p.vertex}"), fragment: include_str!("../shaders/${family}/${p.fragment}"), attributes: &[${pairs(attributes)}], uniforms: &[${pairs(Object.entries(p.uniforms))}] },`);
    }
  }
  const outputs = {
    'src/render-shaders.js': '// Generated by tools/render-shaders.mjs; edit rust/bfe-render/shaders instead.\nexport const shaderSources = ' + JSON.stringify(sources, null, 2) + ';\n',
    'rust/bfe-render/src/program_catalog.rs': '// Generated by tools/render-shaders.mjs; edit the shader manifests instead.\nuse super::Spec;\npub static PROGRAMS: &[Spec] = &[\n' + rows.join('\n') + '\n];\n',
  };
  for (const [path, text] of Object.entries(outputs)) {
    if (check) { if (readFileSync(root + path, 'utf8') !== text) throw Error('Stale ' + path); }
    else writeFileSync(root + path, text);
  }
}
if (process.argv[1] === fileURLToPath(import.meta.url)) generate(process.argv.includes('--check'));
