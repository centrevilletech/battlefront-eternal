// Semantic view facts and native operation traces share one declared boundary.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
const root = fileURLToPath(new URL('../', import.meta.url));
const constant = name => name.replace(/[A-Z]/g, c => '_' + c).toUpperCase();
export function generate(check = false) {
  const schema = JSON.parse(readFileSync(root + 'rust/bfe-render/camera-layout.json'));
  if (schema.version !== 1) throw Error('Unsupported camera layout');
  const fields = rows => {
    let at = 0; const result = {};
    for (const [name, count] of rows) { result[constant(name)] = at; at += count; }
    result.LEN = at; return result;
  };
  const enumerate = rows => Object.fromEntries(rows.map((name, i) => [constant(name), i]));
  const modules = Object.fromEntries(["input","camera","cascade","light","pack","mirror","lens","source","sky","lightInput","lightOutput","shaderFrame"].map(name=>[name,fields(schema[name])]));
  modules.light_command=enumerate(schema.lightCommands);
  modules.light_flag=Object.fromEntries(Object.entries(schema.lightFlags).map(([k,v])=>[constant(k),v]));
  modules.role={...enumerate(schema.roles),COUNT:schema.roles.length};
  modules.limit=Object.fromEntries(Object.entries(schema.limits).map(([k,v])=>[constant(k),v]));
  const notice = '// Generated by tools/render-camera-layout.mjs; edit camera-layout.json instead.\n';
  const outputs = {
    'src/rust-render/camera-layout.js': notice + Object.entries(modules).map(([k,v]) => `export const ${constant(k)} = ${JSON.stringify(v)};\n`).join(''),
    'rust/bfe-render/src/camera_layout.rs': notice + Object.entries(modules).map(([k,v]) => `pub mod ${constant(k).toLowerCase()} {\n` + Object.entries(v).map(([n,x]) => `    pub const ${n}: usize = ${x};`).join('\n') + '\n}\n').join(''),
  };
  for (const [path, text] of Object.entries(outputs)) {
    if (check) { if (readFileSync(root + path, 'utf8') !== text) throw Error('Stale ' + path); }
    else writeFileSync(root + path, text);
  }
}
