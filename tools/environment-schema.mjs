// Generates the numeric boundary of the destruction and weather presentation
// phase (rust/bfe-environment) from its layout, for the page and the Rust
// crate alike: node tools/environment-schema.mjs [--check]. Only offsets and
// strides cross it; no renderer or content object does.
import { readFileSync, writeFileSync } from 'node:fs';

const layout = JSON.parse(readFileSync(new URL('../rust/bfe-environment/layout.json', import.meta.url), 'utf8'));
const upper = (s) => s.replace(/[A-Z]/g, (c, i) => (i ? '_' : '') + c).toUpperCase();
// A number, or "Limits.NAME" naming one of the layout's limits or a record's
// stride, or a product of such (a size known to both sides by one name).
const resolve = (text) => String(text).split('*').reduce((product, token) => {
  token = token.trim();
  if (/^\d+$/.test(token)) return product * Number(token);
  const [owner, field] = token.split('.');
  const value = layout.limits[owner]?.[field.toLowerCase().replace(/_(.)/g, (m, c) => c.toUpperCase())] ?? (field === 'STRIDE' ? strides[owner] : undefined);
  if (value === undefined) throw Error(`layout.json: cannot resolve ${token}`);
  return product * value;
}, 1);
const strides = {};
let js = `// Generated by tools/environment-schema.mjs; do not edit.\nexport const VERSION = ${layout.version};\n`;
let rs = `// Generated by tools/environment-schema.mjs; do not edit.\npub const VERSION: u32 = ${layout.version};\n`;
for (const [name, fields] of Object.entries(layout.records)) {
  let at = 0;
  const values = {};
  for (const [field, n] of Object.entries(fields)) { values[upper(field)] = at; at += resolve(n); }
  values.STRIDE = at;
  strides[name] = at;
  js += `export const ${name} = Object.freeze(${JSON.stringify(values)});\n`;
  rs += `pub mod ${upper(name).toLowerCase()} {\n${Object.entries(values).map(([k, v]) => `    pub const ${k}: usize = ${v};`).join('\n')}\n}\n`;
}
for (const [name, names] of Object.entries(layout.enums)) {
  const values = Object.fromEntries(names.map((n, i) => [upper(n), i]));
  js += `export const ${name} = Object.freeze(${JSON.stringify(values)});\n`;
  rs += `pub mod ${upper(name).toLowerCase()} {\n${Object.entries(values).map(([k, v]) => `    pub const ${k}: f64 = ${v}.0;`).join('\n')}\n}\n`;
}
for (const [name, values] of Object.entries(layout.limits)) {
  const fields = Object.fromEntries(Object.entries(values).map(([k, v]) => [upper(k), v]));
  js += `export const ${name} = Object.freeze(${JSON.stringify(fields)});\n`;
  rs += `pub mod ${upper(name).toLowerCase()} {\n${Object.entries(fields).map(([k, v]) => `    pub const ${k}: usize = ${v};`).join('\n')}\n}\n`;
}
// Named blocks laid end to end: where each entry starts, and the whole's length
// (in the units of the strides given).
for (const [name, block] of Object.entries(layout.blocks || {})) {
  let at = resolve(block.start);
  const values = {};
  for (const [entry, count, stride] of block.entries) { values[upper(entry)] = at; at += resolve(count) * resolve(stride); }
  values.LEN = at;
  js += `export const ${name} = Object.freeze(${JSON.stringify(values)});\n`;
  rs += `pub mod ${upper(name).toLowerCase()} {\n${Object.entries(values).map(([k, v]) => `    pub const ${k}: usize = ${v};`).join('\n')}\n}\n`;
}
for (const [path, value] of [['src/environment/layout.js', js], ['rust/bfe-environment/src/layout.rs', rs]]) {
  const url = new URL('../' + path, import.meta.url);
  if (process.argv.includes('--check')) {
    let have = null;
    try { have = readFileSync(url, 'utf8'); } catch { /* absent counts as stale */ }
    if (have !== value) throw Error(`${path} needs regeneration: node tools/environment-schema.mjs`);
  } else writeFileSync(url, value);
}
