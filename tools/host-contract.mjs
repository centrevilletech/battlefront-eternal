// Hash the complete generated boundary, including operations, imports and byte
// spans. Kind hashes alone cannot detect an incompatible host input layout.
import { createHash } from 'node:crypto';
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
export const ROOT = fileURLToPath(new URL('../', import.meta.url));
export function files(root, directory) {
  return readdirSync(join(root, directory), { withFileTypes: true }).flatMap(entry => {
    const path = join(directory, entry.name);
    return entry.isDirectory() ? files(root, path) : [path];
  }).sort();
}
export function digest(root, paths) {
  const hash = createHash('sha256');
  for (const path of paths.sort()) {
    const bytes = readFileSync(join(root, path));
    hash.update(relative('.', path).replaceAll('\\', '/') + '\0' + bytes.length + '\0');
    hash.update(bytes);
  }
  return hash.digest('hex');
}
export function schemaFingerprint(root = ROOT) {
  return digest(root, ['tools/sim-schema.mjs', ...files(root, 'rust/sim/schema'), ...files(root, 'src/sim/gen')]);
}
export function engineBuild(root = ROOT) {
  const crates = ['sim', 'bfe-node', 'content', 'three', 'v8math', 'jsrt', 'bfe-pose', 'bfe-presentation', 'audio-control'];
  return digest(root, [...files(root, 'src'), ...crates.flatMap(crate => files(root, 'rust/' + crate)),
    'rust/Cargo.toml', 'rust/rust-toolchain.toml', 'rust/Cargo.lock']);
}

export function generate(check = false) {
  const content = '// Generated by tools/host-contract.mjs; do not edit.\nexport const HOST_SCHEMA = ' + JSON.stringify(schemaFingerprint()) + ';\n';
  const path = join(ROOT, 'src/sim/host-schema.js');
  if (check) {
    if (readFileSync(path, 'utf8') !== content) throw Error('Host boundary fingerprint is stale');
  } else writeFileSync(path, content);
}
if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) generate(process.argv.includes('--check'));
