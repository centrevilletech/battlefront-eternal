// One declaration owns the menu/spawn draw record on both sides of WASM.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
const root = fileURLToPath(new URL('../', import.meta.url));
export function generate(check = false) {
  const schema = JSON.parse(readFileSync(root + 'rust/bfe-render/interface-layout.json'));
  const constants = { MAX_DRAWS: schema.maxDraws, MAX_UNIFORMS: schema.maxUniforms, UNIFORM: schema.uniformSize };
  for (let i = 0; i < schema.fields.length; i++) constants[schema.fields[i].replace(/[A-Z]/g, s => '_' + s).toUpperCase()] = i;
  constants.STRIDE = constants.VALUES + constants.MAX_UNIFORMS * constants.UNIFORM;
  const notice = '// Generated by tools/render-interface-layout.mjs; edit interface-layout.json instead.\n';
  const outputs = {
    'src/rust-render/interface-layout.js': notice + 'export const UI = ' + JSON.stringify(constants, null, 2) + ';\n',
    'rust/bfe-render/src/interface_layout.rs': notice + Object.entries(constants).map(([key, value]) => `pub const ${key}: usize = ${value};`).join('\n') + '\n',
  };
  for (const [path, text] of Object.entries(outputs)) {
    if (check) { if (readFileSync(root + path, 'utf8') !== text) throw Error('Stale ' + path); }
    else writeFileSync(root + path, text);
  }
}
