// Line publication carries live positions and placement; GPU policy stays native.
import {readFileSync,writeFileSync} from 'node:fs';
import {fileURLToPath} from 'node:url';
export function generate(check=false){
 const root=fileURLToPath(new URL('../',import.meta.url)),schema=JSON.parse(readFileSync(root+'rust/bfe-render/line-layout.json'));
 const upper=s=>s.replace(/[A-Z]/g,c=>'_'+c).toUpperCase(),layout={},rust=[];
 for(const [name,fields] of Object.entries(schema)){
  let at=0;const row={};for(const [key,size]of Object.entries(fields)){row[upper(key)]=(name==='limit'||name==='kind')?size:at;if(name!=='limit'&&name!=='kind')at+=size;}
  if(name!=='limit'&&name!=='kind')row.LEN=at;layout[upper(name)]=row;
  rust.push('pub mod '+name+' {',...Object.entries(row).map(([key,value])=>'    pub const '+key+':usize='+value+';'),'}');
 }
 const notice='// Generated by tools/render-line-layout.mjs; edit line-layout.json.\n';
 for(const [name,text]of Object.entries({'src/rust-render/line-layout.js':notice+'export const LINE='+JSON.stringify(layout,null,2)+';\n','rust/bfe-render/src/line_layout.rs':notice+rust.join('\n')+'\n'})){
  if(check){if(readFileSync(root+name,'utf8')!==text)throw Error('Stale '+name);}else writeFileSync(root+name,text);
 }
}
if(process.argv[1]===fileURLToPath(import.meta.url))generate(process.argv.includes('--check'));
