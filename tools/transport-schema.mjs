// BFE-UDP/1 and gameplay input names have one source for both device hosts.
// Record widths are bytes; presentation's numeric rows remain independent.
import {readFileSync,writeFileSync} from 'node:fs';
const upper=s=>s.replace(/([a-z0-9])([A-Z])/g,'$1_$2').toUpperCase();
const schema=JSON.parse(readFileSync(new URL('../rust/sim/schema/transport-layout.json',import.meta.url),'utf8'));
let js='// Generated by tools/transport-schema.mjs; do not edit.\n';
let rs='// Generated by tools/transport-schema.mjs; do not edit.\n';
js+=`export const TRANSPORT_VERSION = ${schema.version};\n`;rs+=`pub const VERSION: usize = ${schema.version};\n`;
const group=(name,values)=>{
 js+=`export const ${name} = Object.freeze(${JSON.stringify(values)});\n`;
 rs+=`pub mod ${name.toLowerCase()} {\n`;
 for(const [key,value]of Object.entries(values))rs+=`    pub const ${upper(key)}: ${typeof value==='string'?"&str":value>0xffffffff?'u64':'usize'} = ${JSON.stringify(value)};\n`;
 rs+='}\n';
};
group('NETWORK_CONTRACT',schema.contract);
for(const [name,values]of Object.entries(schema.constants))group(name.toUpperCase(),values);
for(const [name,fields]of Object.entries(schema.records)){
 let at=0;const offsets={};for(const [field,width]of Object.entries(fields)){offsets[upper(field)]=at;at+=width;}offsets.BYTES=at;group(name.toUpperCase(),offsets);
}
for(const [name,values]of [['INPUT_CODES',schema.inputCodes],['INPUT_ACTIONS',schema.inputActions]]){
 js+=`export const ${name} = Object.freeze(${JSON.stringify(values)});\n`;
 rs+=`pub const ${name}: [&str; ${values.length}] = [${values.map(JSON.stringify).join(',')}];\n`;
}
for(const [path,content]of [['src/net/layout.js',js],['rust/bfe-transport/src/layout.rs',rs]]){
 const file=new URL('../'+path,import.meta.url);
 if(process.argv.includes('--check')){if(readFileSync(file,'utf8')!==content)throw Error(path+' needs regeneration');}
 else writeFileSync(file,content);
}
