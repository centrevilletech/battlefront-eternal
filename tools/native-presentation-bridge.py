#!/usr/bin/env python3
"""Reuse the presentation's Rust browser facade as a native session transport."""
from pathlib import Path
import re,json,sys
ROOT=Path(__file__).resolve().parents[1]
s=(ROOT/'rust/bfe-presentation/src/web.rs').read_text()
# These classes deliberately contain transport only. Retaining their bodies
# makes a session exercise the same owned phase methods on either platform.
parts=re.split(r'(?=pub struct Page)',s)[1:]
meta=[];output=['// Generated by tools/native-presentation-bridge.py; do not edit.',
'#![allow(unused_imports, unused_variables, non_camel_case_types)]','use bfe_presentation::*;',
'use crate::session::{Arguments,BlobStore};']
for part in parts:
    cls=re.match(r'pub struct (\w+)',part)[1]; prefix=cls.lower()
    part=re.sub(r'#\[wasm_bindgen(?:\([^\n]*\))?\]\s*','',part)
    # Cosmetic random is a browser primitive, recorded with each coarse call.
    # Native commands borrow those samples; replay never clones a frame tape.
    part=re.sub(r'extern "C"\s*\{\s*fn page_random\(\)\s*->\s*f64;\s*\}', '', part)
    if cls=='PageSniper':
        for method in ['collect','frame']:
            old=f'pub fn {method}(&mut self){{self.inner.{method}(&mut ||page_random());}}'
            new=f'pub fn {method}(&mut self,random:&[f64])->Result<(),String>{{let mut cursor=0;self.inner.{method}(&mut ||{{let value=random.get(cursor).copied().unwrap_or(0.5);cursor+=1;value}});if cursor>random.len(){{return Err(String::from("sniper random service is short"));}}Ok(())}}'
            if old not in part:raise SystemExit('sniper random facade changed')
            part=part.replace(old,new)
    if cls=='PageLightning':
        setup='let mut cursor=0;let mut collision=crate::effects::lightning::RecordedCollision{values:casts,cursor:0};'
        random='&mut ||{let value=random.get(cursor).copied().unwrap_or(0.5);cursor+=1;value}'
        check='if cursor>random.len()||collision.cursor>casts.len(){return Err(String::from("lightning service recording is short"));}'
        replacements=[
            ('pub fn add(&mut self,def:usize,classic:bool,enhanced:bool,host:&crate::effects::lightning_web::Host)->usize{self.inner.add(def,classic,enhanced,&mut ||page_random(),&mut crate::effects::lightning_web::BrowserCollision(host))}',
             'pub fn add(&mut self,def:usize,classic:bool,enhanced:bool,random:&[f64],casts:&[f64])->Result<usize,JsValue>{'+setup+'let result=self.inner.add(def,classic,enhanced,'+random+',&mut collision);'+check+'Ok(result)}'),
            ('pub fn step(&mut self,host:&crate::effects::lightning_web::Host){self.inner.step(&mut ||page_random(),&mut crate::effects::lightning_web::BrowserCollision(host));}',
             'pub fn step(&mut self,random:&[f64],casts:&[f64])->Result<(),JsValue>{'+setup+'self.inner.step('+random+',&mut collision);'+check+'Ok(())}'),
            ('pub fn fixture(&mut self,data:&str,host:&crate::effects::lightning_web::Host)->Result<String,JsValue>{let input=serde_json::from_str(data).map_err(|e|JsValue::from_str(&e.to_string()))?;Ok(self.inner.fixture(input,&mut ||page_random(),&mut crate::effects::lightning_web::BrowserCollision(host)))}',
             'pub fn fixture(&mut self,data:&str,random:&[f64],casts:&[f64])->Result<String,JsValue>{let input=serde_json::from_str(data).map_err(|e|JsValue::from_str(&e.to_string()))?;'+setup+'let result=self.inner.fixture(input,'+random+',&mut collision);'+check+'Ok(result)}')]
        for old,new in replacements:
            if old not in part:raise SystemExit('lightning service facade changed')
            part=part.replace(old,new)
    part=part.replace('crate::','bfe_presentation::').replace('JsValue','String')
    part=re.sub(r'String::from_str\(&e.to_string\(\)\)','e.to_string()',part)
    part=part[:part.rfind('}')+1].replace('String::from_str','String::from')
    # Every field in the native owners is initialized scalar storage. Pointer
    # getters serve browser views; native transports borrow their backing slices.
    methods=[];banks=[]
    for m in re.finditer(r'pub fn (\w+)\((.*?)\)\s*(?:->\s*([^\{]+))?\{',part,re.S):
        start=m.end();depth=1;pos=start
        while depth:
            if part[pos]=='{':depth+=1
            if part[pos]=='}':depth-=1
            pos+=1
        name=m[1];body=part[start:pos-1];args=[]
        for arg in m[2].split(','):
            arg=arg.strip()
            if not arg or arg in ['&self','&mut self']:continue
            n,t=arg.split(':',1);args.append((n.strip(),t.strip()))
        if name.endswith('_ptr'):
            expr=re.search(r'(self\.[\w.()\[\]0-9]+)\.as_ptr\(\)',body)
            if expr and not args:
                bank=name[:-4];scalar=re.search(r'\*const (\w+)',m[3])[1];banks.append((bank,scalar,expr[1]))
            continue
        if name=='bind_network' or cls=='PageFeet' and name=='heights':continue
        if name.endswith('_len') or name in ['new','preview','handles_len','feet_at','bodies_at','actor_node_start','actor_skin_start','view_node_start','slot_input','slot_output','entries_capacity']:continue
        methods.append((name,args,(m[3] or '').strip()))
    joined=[method for method in methods if any(t.startswith('&Page') for _,t in method[1])]
    methods=[method for method in methods if method not in joined]
    output.append(part)
    if cls=='PageUnits':output.append('impl PageUnits {pub fn load_prepared(&mut self,data:bfe_presentation::unit_content::Input)->usize{self.inner.load(data)} pub fn view_prepared(&mut self,data:bfe_presentation::unit_content::FirstPersonInput,attachments:&str)->Result<usize,String>{let attachments:Vec<bfe_presentation::units::Attachment>=serde_json::from_str(attachments).map_err(|e|e.to_string())?;let id=self.inner.view(data);self.inner.view_attach(id,&attachments);Ok(id)}}')
    if cls=='PageNetwork':
        shared={'timeline_input':'timeline.input','timeline_output':'timeline.output','header':'header','records':'leases.records','seats':'leases.seats','payloads':'leases.payloads','publications':'leases.publications','lease_changes':'leases.changes'}
        banks.extend((n,'u8' if n=='payloads' else 'u32' if n in ['seats','publications'] else 'i32' if n=='lease_changes' else 'f64','shared:'+field) for n,field in shared.items())
        output+=['impl PageNetwork {']
        for mutable in [True,False]:
            fn='bank' if mutable else 'read_bank';guard='BankMut' if mutable else 'Bank';borrow='borrow_mut' if mutable else 'borrow';ref='std::cell::RefMut' if mutable else 'std::cell::Ref';by='&mut ' if mutable else '&';view='bytes_mut' if mutable else 'bytes'
            output.append(f"pub fn {fn}(&"+('mut ' if mutable else '')+f"self,name:&str)->Result<crate::session::{guard}<'_>,String>{{match name{{")
            for n,t,e in banks:
                if e.startswith('shared:'):
                    field=e[7:];output.append(f'"{n}"=>Ok(crate::session::{guard}::Shared({ref}::map(self.inner.as_ref().ok_or("network is not initialized")?.{borrow}(),|s|crate::session::{view}({by}s.{field})))),')
                else:output.append(f'"{n}"=>Ok(crate::session::{guard}::Slice(crate::session::{view}({by}{e}))),')
            output.append('_=>Err(format!("unknown network bank {name}")),}}')
        output.append("pub fn bank_lengths(&self)->Vec<(&'static str,usize)>{let s=self.inner.as_ref().map(|s|s.borrow());vec![")
        for n,t,e in banks:output.append(f'("{n}", '+(f's.as_ref().map_or(0,|s|s.{e[7:]}.len())' if e.startswith('shared:') else e+'.len()')+'),')
        output+= [']}','}']
    else:
        output+=['impl '+cls+' {','pub fn bank(&mut self,name:&str)->Result<&mut [u8],String>{match name{']
        for n,t,expr in banks:
            if '(' not in expr:output.append(f'"{n}"=>Ok(crate::session::bytes_mut(&mut {expr})),')
        output+=['_=>Err(format!("unknown presentation input bank {name}")),}}',
        'pub fn read_bank(&self,name:&str)->Result<&[u8],String>{match name{']
        for n,t,expr in banks:output.append(f'"{n}"=>Ok(crate::session::bytes(&{expr})),')
        if cls=='PageOrdnance':
            output.append('_=>{if let Some(i)=name.strip_prefix(\"quad_\").and_then(|s|s.parse::<usize>().ok()).filter(|i|*i<6){return Ok(crate::session::bytes(self.inner.quad_arrays()[i]));}if let Some(i)=name.strip_prefix(\"blaster_\").and_then(|s|s.parse::<usize>().ok()).filter(|i|*i<4){return Ok(crate::session::bytes(self.inner.blaster_arrays()[i]));}Err(format!(\"unknown presentation bank {name}\"))},')
        output+=[('}}' if cls=='PageOrdnance' else '_=>Err(format!("unknown presentation bank {name}")),}}'),'pub fn bank_lengths(&self)->Vec<(&\'static str,usize)>{vec![']
        for n,t,expr in banks:output.append(f'(\"{n}\", {expr}.len()),')
        output+= [']}','}']
    output+=['pub enum '+cls+'Command {']
    def owned(t):return 'String' if t=='&str' else 'Vec<f64>' if t=='&[f64]' else t
    for n,args,r in methods:output.append(n+('('+','.join(owned(t) for _,t in args)+')' if args else '')+',')
    output+=['}', 'impl '+cls+'Command {', 'pub fn decode(name:&str,args:&[serde_json::Value],blobs:&BlobStore)->Result<Self,String>{let a=Arguments::new(args,blobs);Ok(match name{']
    for n,args,r in methods:
        decoded=[]
        for i,(_,t) in enumerate(args):
            ac='string' if t=='&str' else 'f64s' if t=='&[f64]' else t[4:-1]+'s' if t.startswith('Vec<') else t
            decoded.append(f'a.{ac}({i})?')
        output.append(f'"{n}"=>Self::{n}'+('('+','.join(decoded)+')' if args else '')+',')
    output+=['_=>return Err(format!("unknown presentation command {name}")),})}',
        'pub fn execute(&self,host:&mut '+cls+')->Result<(),String>{match self{']
    for n,args,r in methods:
        names=[n for n,t in args];passed=[n if t in ['&str','&[f64]'] else n+'.clone()' if t.startswith('Vec<') else '*'+n for n,t in args]
        call='host.'+n+'('+','.join(passed)+')'
        # Hot page exchanges return primitive statuses to avoid JS result
        # tuples. Native sessions still propagate their cold error channel.
        if cls=='PageNetwork' and n in ['receive','outbound_run','outbound_batch']:
            body='if !'+call+' {return Err(host.take_network_error());}'
        elif cls=='PageNetwork' and n in ['encode','encode_outbound']:
            body='if '+call+' == -1 {return Err(host.take_network_error());}'
        else:body='let _='+call+('?' if r.startswith('Result') else '')+';'
        output.append('Self::'+n+('('+','.join(names)+')' if args else '')+'=>{'+body+'},')
    output+=['}Ok(())}}']
    ctor=re.search(r'pub fn new\((.*?)\)',part,re.S)[1]
    ctor_args=[a.strip().split(':',1) for a in ctor.split(',') if a.strip()]
    meta.append({'constructorArgs':ctor_args,'class':prefix,'name':cls,'methods':[{'name':n,'args':a,'result':r} for n,a,r in methods+joined]+([{'name':'bind_network','args':[['network','&PageNetwork'],['slot','usize'],['id','f64'],['generation','f64'],['kind','f64']],'result':'Result<(),String>'}] if cls in ['PageUnits','PageVehicles'] else []),
        'banks':[{'name':n,'type':t,'pointer':n+'_ptr','length':n+'_len'} for n,t,e in banks]})
for file,contents in [(ROOT/'rust/bfe-client/src/presentation_bridge.rs','\n'.join(output)+'\n'),(ROOT/'tools/native-session/presentation-api.json',json.dumps(meta,indent=2)+'\n')]:
    if '--check' in sys.argv:
        if not file.exists() or file.read_text()!=contents:raise SystemExit(f'{file.name} is stale')
    else:file.write_text(contents)
