// Retained post facts and temporal state share one declared WASM layout.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
const root = fileURLToPath(new URL('../', import.meta.url));
const constant = name => name.replace(/[A-Z]/g, s => '_' + s).toUpperCase();
export function generate(check = false) {
  const schema = JSON.parse(readFileSync(root + 'rust/bfe-render/post-chain-layout.json'));
  if (schema.version !== 1) throw Error('Unsupported post layout');
  const offsets = fields => {
    const out = {}; let at = 0;
    for (const [name, size] of fields) { out[constant(name)] = at; at += size; }
    out.LEN = at; return out;
  };
  const resources = Object.fromEntries(schema.resources.map((name, i) => [constant(name), i]));
  Object.assign(resources, Object.fromEntries(schema.resourceFields.map((name, i) => [constant(name), i])));
  resources.STRIDE = schema.resourceFields.length; resources.COUNT = schema.resources.length;
  const facts = offsets(schema.facts), state = offsets(schema.state);
  facts.RESOURCES = facts.LEN; facts.PROGRAMS = facts.RESOURCES + resources.COUNT * resources.STRIDE;
  facts.LEN = facts.PROGRAMS + Object.keys(schema.programs).length;
  const programs = Object.fromEntries(Object.keys(schema.programs).map((name, i) => [constant(name), i]));
  const keys = Object.values(schema.programs);
  const manifest = JSON.parse(readFileSync(root + 'rust/bfe-render/shaders/post-hud/manifest.json'));
  const declarations = keys.map(key => {
    const row = manifest.programs.find(p => p.key === key);
    if (!row) throw Error('Missing post program ' + key);
    return Object.entries(row.uniforms);
  });
  const modules = { facts, state, resource: resources, program: { ...programs, COUNT: keys.length }, mode: Object.fromEntries(Object.entries(schema.modes).map(([k,v]) => [constant(k),v])), aa: Object.fromEntries(Object.entries(schema.aa).map(([k,v]) => [constant(k),v])) };
  const notice = '// Generated by tools/render-post-layout.mjs; edit post-chain-layout.json instead.\n';
  const rust = Object.entries(modules).map(([name, values]) => `pub mod ${name} {\n` + Object.entries(values).map(([key, value]) => `    pub const ${key}: usize = ${value};`).join('\n') + '\n}\n').join('');
  const uniformModules = Object.keys(schema.programs).map((name, i) => `pub mod ${constant(name).toLowerCase()} {\n` + declarations[i].map(([name], slot) => `    pub const ${constant(name)}: usize = ${slot};`).join('\n') + '\n}\n').join('');
  const types = declarations.map(ds => '&[' + ds.map(([,ty]) => typeof ty === 'number' ? ty : ty.type).join(', ') + ']').join(', ');
  const outputs = {
    'src/rust-render/post-layout.js': notice + Object.entries(modules).map(([name, values]) => `export const ${name.toUpperCase()} = ${JSON.stringify(values)};\n`).join('') + `export const POST_KEYS = ${JSON.stringify(keys)};\n`,
    'rust/bfe-render/src/post_chain_layout.rs': notice + rust + `pub const TYPES: [&[u32]; ${keys.length}] = [${types}];\n` + 'pub mod uniform {\n' + uniformModules + '}\n',
  };
  for (const [path, text] of Object.entries(outputs)) {
    if (check) { if (readFileSync(root + path, 'utf8') !== text) throw Error('Stale ' + path); }
    else writeFileSync(root + path, text);
  }
}
