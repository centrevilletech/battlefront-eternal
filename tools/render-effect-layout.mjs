// Effect producer rows are a data boundary, independent of GPU descriptors.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
const root = fileURLToPath(new URL('../', import.meta.url));
export function generate(check = false) {
  const rows = JSON.parse(readFileSync(root + 'rust/bfe-render/effect-layout.json'));
  const targets = JSON.parse(readFileSync(root + 'rust/bfe-render/effect-targets.json'));
  const upper = s => s.replace(/[A-Z]/g, c => '_' + c).toUpperCase();
  const notice = '// Generated by tools/render-effect-layout.mjs; edit effect-layout.json instead.\n';
  const layouts = {}, rust = [], producers = [], environment = [];
  for (const [id, [name, row]] of Object.entries(rows).entries()) {
    let at = 0; const fields = { ID: id };
    for (const [key, size] of Object.entries(row.values)) { fields[upper(key)] = at; at += size; }
    if(row.capacity)fields.CAPACITY=row.capacity;
    fields.LENGTH = at; fields.STRIDE = Object.values(row.attributes).reduce((a,b)=>a+b,0);
    layouts[upper(name)] = fields;
    environment.push(`pub mod ${upper(name).toLowerCase()} {\n${Object.entries(fields).map(([key,value])=>`    pub const ${key}: usize = ${value};`).join('\n')}\n}`);
    const pairs = fields => Object.entries(fields).map(([name,size])=>`(${JSON.stringify(name)},${size})`).join(",");
    producers.push(`    (&[${pairs(row.attributes)}],&[${pairs(row.values)}]),`);
    rust.push(`pub const ${upper(name)}: usize = ${id};`);
    if(row.capacity)rust.push(`pub const ${upper(name)}_CAPACITY:usize=${row.capacity};`);
  }
  const targetJs='export const EFFECT_TARGET = '+JSON.stringify(Object.fromEntries(Object.entries(targets).map(([k,v])=>[upper(k),v])),null,2)+';\n';
  const targetRust=Object.entries(targets).map(([k,v])=>`pub const TARGET_${upper(k)}: usize = ${v};`).join('\n')+'\n';
  const outputs = {
    'rust/bfe-environment/src/effect_layout.rs': notice + environment.join('\n') + '\n',
    'src/rust-render/effect-layout.js': notice + 'export const EFFECT = ' + JSON.stringify(layouts, null, 2) + ';\n'+targetJs+'export const EFFECT_INPUTS = '+JSON.stringify(Object.values(rows).map(row=>Object.entries(row.attributes)))+';\n',
    'rust/bfe-render/src/effect_layout.rs': notice + rust.join('\n') + '\npub const PRODUCERS: &[(&[(&str,u32)],&[(&str,u32)])] = &[\n' + producers.join('\n') + '\n];\n'+targetRust,
  };
  for (const [path, text] of Object.entries(outputs)) {
    if (check) { if (readFileSync(root + path, 'utf8') !== text) throw Error('Stale ' + path); }
    else writeFileSync(root + path, text);
  }
}
if (process.argv[1] === fileURLToPath(import.meta.url)) generate(process.argv.includes('--check'));
