// Cold static-resource transport shares one generated layout with Rust.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
const root = fileURLToPath(new URL('../', import.meta.url));
export function generate(check = false) {
  const schema = JSON.parse(readFileSync(root + 'rust/bfe-render/static-layout.json'));
  const upper = s => s.replace(/[A-Z]/g, c => '_' + c).toUpperCase();
  const notice = '// Generated by tools/render-static-layout.mjs; edit static-layout.json instead.\n';
  const outputs = {
    'src/rust-render/static-layout.js': notice + 'export const STATIC = ' + JSON.stringify(Object.fromEntries(Object.entries(schema).map(([name, fields]) => [upper(name), Object.fromEntries(Object.entries(fields).map(([key, value]) => [upper(key), value]))])), null, 2) + ';\n',
    'rust/bfe-render/src/static_layout.rs': notice + Object.entries(schema).flatMap(([name, fields]) => Object.entries(fields).map(([key, value]) => `pub const ${upper(name)}_${upper(key)}: usize = ${value};`)).join('\n') + '\n',
  };
  for (const [path, text] of Object.entries(outputs)) {
    if (check) { if (readFileSync(root + path, 'utf8') !== text) throw Error('Stale ' + path); }
    else writeFileSync(root + path, text);
  }
}
if (process.argv[1] === fileURLToPath(import.meta.url)) generate(process.argv.includes('--check'));
