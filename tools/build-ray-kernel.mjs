// Builds the collision world's ray kernel (rust/rays) for WebAssembly and
// writes src/ray-kernel-wasm.js: the module's bytes as base64, so the world
// worker (bundled by Vite), the page and plain Node (the dedicated server,
// tools/world-hash.mjs) all load it as a JavaScript import, with no wasm
// asset to serve, unpack or stub.
//
//   node tools/build-ray-kernel.mjs        (needs cargo and the
//                                           wasm32-unknown-unknown target)
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('../', import.meta.url));
const build = spawnSync('cargo', ['build', '--release', '--target', 'wasm32-unknown-unknown', '-p', 'rays', ...(process.env.CARGO_JOBS ? ['-j', process.env.CARGO_JOBS] : [])],
  { cwd: `${root}rust`, stdio: 'inherit' });
if (build.error || build.status) throw build.error || Error(`cargo failed (${build.status})`);
const bytes = readFileSync(`${root}rust/target/wasm32-unknown-unknown/release/rays.wasm`);
new WebAssembly.Module(bytes);
const rustc = spawnSync('rustc', ['--version'], { encoding: 'utf8' }).stdout.trim();
const sha = createHash('sha256').update(bytes).digest('hex');
const lines = bytes.toString('base64').match(/.{1,120}/g);
writeFileSync(`${root}src/ray-kernel-wasm.js`, `// Generated by tools/build-ray-kernel.mjs from rust/rays (${rustc}); do not edit.
// ${bytes.length} bytes, sha256 ${sha}.
export const RAY_KERNEL_WASM =
${lines.map((line) => `  "${line}"`).join(' +\n')};
`);
console.log(`src/ray-kernel-wasm.js: ${bytes.length} bytes of WebAssembly, sha256 ${sha.slice(0, 16)}`);
