// Actor appearance and source handles use a generated numeric boundary.
import {readFileSync,writeFileSync} from 'node:fs';
import {fileURLToPath} from 'node:url';
export function generate(check=false){
 const root=fileURLToPath(new URL('../',import.meta.url)),schema=JSON.parse(readFileSync(root+'rust/bfe-render/actor-layout.json'));
 const upper=s=>s.replace(/[A-Z]/g,c=>'_'+c).toUpperCase(),layout={},rust=[];
 for(const [name,fields] of Object.entries(schema)){
  let at=0;const row={};for(const [key,size]of Object.entries(fields)){row[upper(key)]=(name==='limit'||name==='kind'||name==='crowd')?size:at;if(name!=='limit'&&name!=='kind'&&name!=='crowd')at+=size;}
  if(name!=='limit'&&name!=='kind'&&name!=='crowd')row.LEN=at;layout[upper(name)]=row;
  rust.push('pub mod '+name.replace(/[A-Z]/g,c=>'_'+c.toLowerCase())+' {',...Object.entries(row).map(([key,value])=>'    pub const '+key+':'+(value<0?'i32':'usize')+'='+value+';'),'}');
 }
 const notice='// Generated by tools/render-actor-layout.mjs; edit actor-layout.json.\n';
 for(const [name,text]of Object.entries({'src/rust-render/actor-layout.js':notice+'export const ACTOR='+JSON.stringify(layout,null,2)+';\n','rust/bfe-render/src/actor_layout.rs':notice+rust.join('\n')+'\n'})){
  if(check){if(readFileSync(root+name,'utf8')!==text)throw Error('Stale '+name);}else writeFileSync(root+name,text);
 }
}
if(process.argv[1]===fileURLToPath(import.meta.url))generate(process.argv.includes('--check'));
